/**
 * Словарь машинного текста.
 *
 * Границу слова здесь нельзя писать через \b: в JavaScript она определяется
 * через [A-Za-z0-9_], и перед кириллицей не срабатывает вообще. По той же
 * причине нельзя писать \w для окончания: «ключев\w+» требует латиницы
 * после кириллического корня и не ловит «ключевой». Обе ошибки выглядели
 * как правильные шаблоны и обе прошли бы без этой проверки.
 *
 * Запрет в промпте полагается на память модели и протекает: «ключевой»
 * стояло в запрете прямым текстом и всё равно прошло в дайджест. Словарь
 * не полагается — он проверяет готовый текст.
 *
 * Гейт только сообщает, а не отбрасывает материал: одно слово не повод
 * лишить читателя новости. Число попаданий пишется в статистику прогона,
 * и если оно растёт — виновата формулировка промпта, а не отдельный день.
 */
const PATTERNS: [RegExp, string][] = [
  [/(?<!\p{L})ключев\p{L}*/iu, "оценка вместо факта"],
  [/(?<!\p{L})уникальн\p{L}*/iu, "оценка вместо факта"],
  [/(?<!\p{L})инновацион\p{L}*/iu, "оценка вместо факта"],
  [/(?<!\p{L})прорывн\p{L}*/iu, "оценка вместо факта"],
  [/(?<!\p{L})революцион\p{L}*/iu, "оценка вместо факта"],
  [/(?<!\p{L})значим\w+ (?:шаг|веха|событие)/iu, "оценка вместо факта"],
  [/стоит отметить/iu, "зачин"],
  [/важно понимать/iu, "зачин"],
  [/давайте разбер/iu, "зачин"],
  [/в современном мире/iu, "зачин"],
  [/не секрет,? что/iu, "зачин"],
  [/(?<!\p{L})эксперты (?:считают|полагают|отмечают)/iu, "ссылка на безымянных"],
  [/исследования показывают/iu, "ссылка на безымянных"],
  [/как известно/iu, "ссылка на безымянных"],
  [/является инструментом/iu, "глагол-пустышка"],
  [/позволяет осуществ/iu, "глагол-пустышка"],
  [/выступает в (?:роли|качестве)/iu, "глагол-пустышка"],
  [/\d+[\s\u2011-]?километр\p{L}*/iu, "единица словом"],
  [/\d+\s?минут\p{L}*/iu, "единица словом"],
  [/\d+\s?секунд\p{L}*/iu, "единица словом"],
  [/\d+\s?килограмм\p{L}*/iu, "единица словом"],
  [/\d+\s?процент\p{L}*/iu, "единица словом"],
  [/\d+\s?миллион\p{L}*/iu, "единица словом"],
  [/\d+\s?тысяч\p{L}*/iu, "единица словом"],
  [/\d{4}\s?год[ауе]\b/iu, "единица словом"],
  // Объявление связи вместо связи. Промпт запрещает эту форму прямым
  // текстом и всё равно её пропускает: «может быть полезен читателю для
  // анализа данных» выглядит как ответ на вопрос «зачем мне это», а делать
  // после него нечего. Ось этого не различает — она засчитывает упоминание
  // читателя за связь, поэтому ловить форму приходится здесь.
  // Корень пишется до беглой гласной: «полезен» не содержит «полезн»,
  // и шаблон с полной основой выглядел бы верным, не поймав ничего.
  [/(?:полез|пригод|интерес)\p{L}* (?:для )?(?:читател\p{L}*|ему|вам)/iu, "объявленная связь"],
  [/(?:может|мог\p{L}+) (?:быть )?(?:полез|пригод)\p{L}*/iu, "объявленная связь"],
  [/(?:в его|в вашем|для его|для вашего) (?:проект\p{L}*|стек\p{L}*|работ\p{L}*)/iu, "объявленная связь"],
  // Пустое подлежащее перед выводом. Читатель только что прочёл, о чём речь,
  // и «эта ситуация» перед мыслью — слово, потраченное на разгон.
  [/(?<!\p{L})эт(?:о|а ситуация|от случай|и данные) (?:демонстрир|показыв|иллюстрир|означа|говорит о том)/iu, "разгон перед выводом"],
  [/(?<!\p{L})данн(?:ый|ая) (?:случай|ситуация|пример)/iu, "разгон перед выводом"],
  [/таким образом,/iu, "итог в конце"],
  [/подводя итог/iu, "итог в конце"],
  [/в заключение/iu, "итог в конце"],
];

export type LexiconHit = { term: string; reason: string };

export function checkLexicon(text: string): LexiconHit[] {
  const hits: LexiconHit[] = [];
  for (const [pattern, reason] of PATTERNS) {
    const match = text.match(pattern);
    if (match) hits.push({ term: match[0], reason });
  }
  return hits;
}

/**
 * Повтор заголовка первой строкой: читатель платит за одну мысль дважды.
 *
 * Мера лексическая и ловит не всё: пересказ другими словами она пропустит,
 * и честнее это признать, чем делать вид, что проверка полная. Но число из
 * заголовка, повторённое в первом предложении, — надёжный признак даже при
 * небольшом совпадении слов: заголовок уже назвал его, называть второй раз
 * незачем.
 */
export function repeatsHeadline(title: string, summary: string): boolean {
  const words = (text: string) =>
    new Set(
      text
        .toLowerCase()
        .replace(/[^\p{L}\p{N}\s]+/gu, " ")
        .split(/\s+/)
        .filter((word) => word.length > 3),
    );

  const numbers = (text: string) =>
    new Set((text.match(/\d[\d\s.,]*\d|\d/g) ?? []).map((n) => n.replace(/\s/g, "")).filter((n) => n.length > 1));

  const first = summary.split(/(?<=[.!?])\s/)[0] ?? "";
  const fromTitle = words(title);
  const fromFirst = words(first);
  if (fromTitle.size === 0 || fromFirst.size === 0) return false;

  let shared = 0;
  for (const word of fromTitle) if (fromFirst.has(word)) shared++;
  const overlap = shared / fromTitle.size;

  const titleNumbers = numbers(title);
  const firstNumbers = numbers(first);
  const repeatsNumber = [...titleNumbers].some((n) => firstNumbers.has(n));

  return overlap > 0.5 || (repeatsNumber && overlap > 0.2);
}

/**
 * Механическая сложность текста: слов в предложении и доля длинных слов.
 *
 * Ползунок сложности меняет промпт, а изменился ли текст — на глаз не видно:
 * двенадцать описаний в день читаются нормально при любом положении. Модель
 * спрашивать незачем, два этих числа считаются даром и не врут о направлении:
 * упало и то и другое — текст стал проще.
 *
 * Мера грубая: она не знает, что «инференс» труднее «поэтому». Смысл её
 * в ряду по дням рядом с положением ползунка, а не в отдельном значении.
 */
export function readability(text: string): { perSentence: number; longShare: number } {
  const sentences = text.split(/(?<=[.!?…])\s+/).filter((part) => /\p{L}/u.test(part));
  const words = text.match(/\p{L}[\p{L}\p{N}-]*/gu) ?? [];
  if (sentences.length === 0 || words.length === 0) return { perSentence: 0, longShare: 0 };
  const long = words.filter((word) => word.length >= 12).length;
  return {
    perSentence: words.length / sentences.length,
    longShare: long / words.length,
  };
}
