/**
 * Язык интерфейса.
 *
 * Два, а не пятнадцать: язык выпуска читатель выбирает из длинного списка,
 * потому что там переводит модель и стоит это ровно столько же. Интерфейс
 * переводят руками, и каждый язык — это ещё один словарь, который кто-то
 * обязан держать в согласии с остальными. Третий появится, когда появится
 * тот, кто его напишет и будет дописывать дальше.
 *
 * Английский первый и он же по умолчанию: продукт выходит за пределы
 * русского языка, и следующий читатель приходит не оттуда, откуда пришли
 * первые. Уже заведённым миграция 0042 оставила русский.
 */
export const LOCALES = ["en", "ru"] as const;

export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "en";

/**
 * Язык назван на себе самом, а не на языке интерфейса: «Russian» ищет глазами
 * тот, кто и так читает по-английски, а тот, кому нужен русский, ищет
 * «Русский». Переключатель языка — единственное место, где это правило
 * важнее единообразия.
 */
export const LOCALE_LABELS: Record<Locale, string> = {
  en: "English",
  ru: "Русский",
};

/**
 * Незнакомое значение читается как язык по умолчанию, а не падает: колонка
 * свободная, и опечатка в ней не должна оставлять читателя без интерфейса.
 */
export const localeOf = (value: string | null | undefined): Locale =>
  (LOCALES as readonly string[]).includes(value ?? "") ? (value as Locale) : DEFAULT_LOCALE;
