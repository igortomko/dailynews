/**
 * Рычаги второго варианта черновика и проверка слабых мест.
 *
 * Отдельно от `pipeline/post.ts`, потому что проверку зовёт и браузер:
 * подсказка пересчитывается, пока автор правит текст, — иначе она говорила
 * бы о черновике, которого на экране уже нет. Сборщик промпта с сетью
 * и ключами в клиентский бандл уезжать не должен.
 */
import type { NetworkId } from "./networks";

/**
 * Рычаги второго варианта. Первый вариант пишется «как он», второй — тем же
 * голосом плюс ровно один рычаг: два рычага сразу не дают понять, какой
 * сработал. Каждый — из корпуса `tg-viral-post`/`news-take` (962 поста
 * верхних тиров, 304 на чужом материале), а не из общих советов:
 *
 *   number     хук с числом: 47% в верхнем тире, пересылки 2.96%
 *   confession признание первой строкой: 54% в верхнем тире
 *   verdict    вердикт вместо пересказа: короткая реакция держится
 *              наравне с длинным постом, пересказ без позиции — дно
 *   segment    названный круг: «многие» комментариев не даёт
 *   specifics  цифры, имена, даты вместо общих слов: пересылки почти вдвое
 *
 * Какой рычаг взят, пишется в `reader_posts.lever`, и `drafts:report`
 * сводит взятое и просмотры по рычагам: так видно, что работает у него,
 * а не в среднем по чужим каналам.
 */
export const LEVERS = {
  number: "первая строка несёт число из материала",
  confession: "первая строка — неудобное признание автора, новость идёт триггером",
  verdict: "первая строка — вердикт автора, пересказ сжат до одной строки после него",
  segment: "прямо назван круг, кого это касается: «если ты нанимаешь в ЕС», а не «многим»",
  specifics: "каждая общая фраза заменена цифрой, именем или датой из материала",
} as const;
export type LeverId = keyof typeof LEVERS;
export const isLever = (value: unknown): value is LeverId =>
  typeof value === "string" && value in LEVERS;

/**
 * Слабые места черновика — код, а не модель: проверка бесплатна и не
 * спорит сама с собой. Каждое — провал из корпуса, а не вкус:
 *
 *   company   вход «OpenAI выпустила…» — самый слабый на чужом материале
 *   no_number ни одной цифры в посте длиннее реплики: конкретика почти
 *             вдвое поднимает пересылки
 *   middle    300–900 знаков в Telegram: хуже и реакции, и разбора
 *   ask       «что думаете?» в конце — худший призыв корпуса
 *
 * Подсказка, а не запрет: автор может так и хотеть. Тревога, горящая
 * на каждом посте, не отличается от выключенной, поэтому их четыре.
 */
export type WeakSpot = "company" | "no_number" | "middle" | "ask";

const OPENING_VERBS =
  "выпустил|выпустила|выпустили|запустил|запустила|запустили|представил|представила|представили|" +
  "анонсировал|анонсировала|анонсировали|объявил|объявила|объявили|купил|купила|купили|" +
  "launched|launches|released|releases|announced|announces|unveiled|unveils|introduced|introduces";

export function weakSpots(network: NetworkId, text: string): WeakSpot[] {
  const spots: WeakSpot[] = [];
  const first = text.trim().split("\n")[0] ?? "";
  // «Я запустил…» — это признание, а не заметка о компании: местоимение
  // тоже с большой буквы, и без исключения тревога горела бы на лучшем входе.
  if (new RegExp(`^(?!(?:Я|Мы|Он|Она|Они|Ты|Вы|I|We|He|She|They|You)\\s)\\p{Lu}[\\p{L}\\p{N}.&-]*(?:\\s+\\p{Lu}[\\p{L}\\p{N}.&-]*){0,2}\\s+(?:${OPENING_VERBS})(?![\\p{L}])`, "u").test(first)) {
    spots.push("company");
  }
  const body = text.replace(/https?:\/\/\S+/g, "");
  if (body.length > 200 && !/\d/.test(body)) spots.push("no_number");
  if (network === "telegram" && text.length > 300 && text.length < 900) spots.push("middle");
  const last = text.trim().split("\n").filter((line) => line.trim()).at(-1) ?? "";
  if (/(что думаете|как вам|а вы как считаете|что скажете|what do you think|thoughts)\s*\?*\s*$/i.test(last)) {
    spots.push("ask");
  }
  return spots;
}

