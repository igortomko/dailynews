import { setInterval } from "node:timers";
import postgres from "postgres";

/**
 * Прямое подключение к Postgres, а не supabase-js: продуктовые схемы
 * не экспонируются в PostgREST (правило 6 инфра-документа), поэтому
 * REST-клиент до схемы dailynews всё равно не достаёт.
 *
 * DATABASE_URL — строка пулера. У прямого хоста только IPv6, а ни Vercel,
 * ни раннеры GitHub Actions по нему не ходят.
 */
const url = process.env.DATABASE_URL;
if (!url) throw new Error("DATABASE_URL не задан");

const host = (() => {
  try {
    return new URL(url).hostname;
  } catch {
    return "";
  }
})();
const isLocal = host === "localhost" || host === "127.0.0.1" || host === "::1";

export const sql = postgres(url, {
  // Транзакционный пулер не поддерживает prepared statements.
  prepare: false,
  // Сертификат подписан собственным CA Supabase: строгая проверка падает
  // на рукопожатии. Соединение остаётся зашифрованным.
  // Локальный Postgres (разработка, db/verify.ts) TLS не слушает вовсе.
  ssl: isLocal ? false : { rejectUnauthorized: false },
  // Транзакционный пулер держит соединение к Postgres только на время
  // запроса, но одновременно идущих запросов у роли всё равно не больше
  // десяти (connection limit, общий с пайплайном): пять здесь и пять
  // у прогона (DB_POOL_MAX в digest.yml) — ровно предел. Шапка ленты уходит
  // шестью запросами; выпуск и его заказ стоят в очереди первыми.
  max: Number(process.env.DB_POOL_MAX ?? 5),
  // Соединение к пулеру стоит DNS, TCP, TLS и SCRAM — из контейнера это
  // 150–500 мс под лимитом CPU, и лента после двадцати секунд простоя
  // открывалась вдвое дольше (замер 21 сентября 2026: 980 мс против 494).
  // Веб держит соединения тёплыми полчаса; простаивающее соединение
  // к транзакционному пулеру не занимает ничего. Пайплайн и скрипты
  // оставляют прежние двадцать секунд: у них процесс должен завершиться
  // сам, не дожидаясь, пока пул отпустит сокеты.
  idle_timeout: process.env.NEXT_RUNTIME ? 1800 : 20,
  connect_timeout: 15,
});

// Раз в пять минут веб трогает пул. Соединение, которое не простаивает,
// не закрывается по idle_timeout, а переоткрытие по max_lifetime (час)
// приходится на этот тик, а не на первый заход читателя после долгой
// паузы — он платил за DNS, TCP, TLS и SCRAM 150–500 мс. unref: таймер
// не держит процесс, и сборка образа (у неё DATABASE_URL — заглушка)
// его не ждёт; отказ заглушки глотается — это не запрос читателя.
// setInterval взят из node:timers явно: с `lib: dom` в tsconfig глобальный
// мог бы разрешиться в браузерную сигнатуру без unref, смотря по порядку
// подключения типов.
if (process.env.NEXT_RUNTIME) {
  setInterval(() => {
    sql`select 1`.catch(() => {});
  }, 5 * 60 * 1000).unref();
}
