import { count } from "./plural";

/**
 * Был ли источник полезен лично этому читателю — и стоит ли его убрать.
 *
 * Числа считает запрос (`getSourceHealth`), а решение принимается здесь:
 * оно нужно и странице источников, которая целиком клиентская, и тесту,
 * а queries.ts помечен server-only и ни туда, ни туда не ходит.
 *
 * Все числа — за одно окно в тридцать дней. Разные окна у соседних чисел
 * в одной строке — это отказ, выглядящий как успех: «дал 42, открыл 1»
 * верно по отдельности и ложно вместе.
 */
export type SourceYield = {
  /** Сколько материалов дал за тридцать дней. */
  items: number;
  /** Сколько из них оказались перепечатками уже собранного. */
  duplicates: number;
  /** Сколько дошло до выпусков этого читателя, а не до чьих-нибудь. */
  in_my_digests: number;
  /**
   * Сколько из них попалось ему на глаза в ленте.
   *
   * Знаменатель здесь именно показанное, а не попавшее в выпуск: неделю
   * не заходил — материалы в выпусках есть, открытий нет, и по ним источник
   * выглядел бы бесполезным. Убрать хороший источник за отпуск читателя —
   * ровно та ошибка, ради которой эта страница и заводится.
   */
  shown: number;
  /** Сколько он раскрыл или по скольким ушёл к источнику. */
  opened: number;
};

/**
 * Со скольких показанных карточек «ни одной не открыл» что-то значит.
 *
 * Ниже этого числа совпадение неотличимо от сигнала: пять новостей мимо —
 * обычная неделя, а не приговор источнику. Цена ошибки несимметрична, как
 * и в дедупе: промолчали о мусорном источнике — он даёт ещё месяц мусора;
 * предложили убрать живой — читатель убрал, и больше этого голоса
 * не услышит. На живом наборе из восемнадцати источников порог в пять
 * показов звал убрать блог, у которого их всего семь, — а десять оставил
 * только тех, у кого двадцать и четырнадцать подряд прошли мимо.
 */
export const ENOUGH_SHOWN = 10;

/** Столько же материалов нужно, чтобы доля перепечаток была долей, а не случаем. */
export const ENOUGH_ITEMS = 10;

/**
 * Ниже какой доли открытий источник перестаёт читаться.
 *
 * Не «ноль открытий»: одно открытие за сорок показов — это тот же ответ,
 * что и ноль, а правило по строгому нулю снимается ровно одним случайным
 * нажатием и больше не возвращается никогда. Одно на десять — граница,
 * при которой на минимуме показов кандидатом остаётся только чистый ноль,
 * а дальше порог смягчается сам: на сорока показах одно открытие его
 * не спасает.
 */
export const RARELY_OPENED = 0.1;

/**
 * С какой доли перепечаток источник пересказывает соседей.
 *
 * Половина — намеренно много. Тревога, горящая на обычном состоянии, ничем
 * не отличается от выключенной, а десяток процентов повторов есть у любого
 * агрегатора просто по устройству.
 */
export const MOSTLY_DUPLICATES = 0.5;

/**
 * Почему этот источник стоит убрать, или null, если не стоит.
 *
 * Поводов два, и порядок не случаен: «не читаешь» сильнее «повторяется».
 * Перепечатка, которую всё равно открывают, ленте не мешает, а источник,
 * из которого не открыли ни одной новости за месяц, не мешает ничем,
 * кроме занятого места в выпуске — и это место у него забирает кто-то
 * непрочитанный, а не кто-то лишний.
 *
 * Причина возвращается строкой с числами, а не кодом: решение принимает
 * читатель, а «источник неэффективен» — это не то, по чему можно решить.
 * Числительное в обеих причинах стоит не подлежащим намеренно: «21 новость
 * попалось» рассогласовано, а проверяют такие строки на двенадцати. Род
 * не назван по той же причине: читателей много, и «ты не открыл» половине
 * из них говорит о ком-то другом.
 */
export function cleanupReason(source: SourceYield): string | null {
  if (source.shown >= ENOUGH_SHOWN && source.opened / source.shown < RARELY_OPENED) {
    const opened = source.opened === 0
      ? "ни одного открытия"
      : count(source.opened, "открытие", "открытия", "открытий");
    const shown = count(
      source.shown, "показанную новость", "показанные новости", "показанных новостей",
    );
    return `${opened} на ${shown}`;
  }
  if (source.items >= ENOUGH_ITEMS && source.duplicates / source.items >= MOSTLY_DUPLICATES) {
    return `${source.duplicates} из ${count(source.items, "новости", "новостей", "новостей")} — перепечатки: то же самое приходит из других источников`;
  }
  return null;
}
