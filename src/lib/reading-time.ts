/**
 * Сколько времени займёт выпуск.
 *
 * Обещается время чтения нашего текста — заголовка и описания, — а не статьи
 * за ссылкой. Длина оригинала гуляет от заметки в абзац до лонгрида на час,
 * и обещание, собранное из неё, обещало бы чужой размер: читатель просил
 * двадцать минут у нас, а получил бы двадцать минут чужого сайта. Свои
 * описания меряются точно — они уже написаны и лежат в `digest_items`.
 *
 * Считаются знаки, а не слова. В японском, китайском и корейском пробелов
 * между словами нет, и `\p{L}+` посчитал бы предложение одним словом: счёт
 * слов врал бы в разы ровно там, где проверить это некому. Знак считается
 * одинаково у всех шестнадцати языков.
 */
import { DEFAULT_COMPLEXITY, SOURCE_LANGUAGE, type Voice } from "./voice";
import { plural } from "./plural";

/**
 * Знаков в минуту при чтении с пониманием.
 *
 * Русские 960 — это примерно 150 слов в минуту при слове в 6,4 знака.
 * Не 250–300: так просматривают, а не читают, а здесь текст плотный,
 * с числами и названиями. Иероглифические языки стоят особняком — знак
 * там несёт слог или слово целиком, и в минуту их проходит втрое меньше.
 *
 * Это порядок величины из работ о скорости чтения, а не замер на наших
 * читателях, и это ручка настройки: окажется, что двадцать минут читаются
 * за пятнадцать — правится здесь одной строкой, и ничего больше об этом
 * знать не надо. Ключи — строки из `LANGUAGES`: язык в базе лежит свободным
 * текстом, и незнакомое значение берёт общее число, а не падает.
 */
const CHARS_PER_MINUTE: Record<string, number> = {
  // Без перевода выпуск остаётся на языке источника, а это почти всегда
  // английский: считать его по русской мерке значит завышать время у всех,
  // кто перевод не включал.
  [SOURCE_LANGUAGE]: 1050,
  английском: 1050,
  русском: 960,
  украинском: 960,
  "португальском (бразильский вариант)": 1000,
  испанском: 1000,
  итальянском: 1000,
  французском: 1000,
  нидерландском: 950,
  немецком: 900,
  польском: 930,
  турецком: 950,
  арабском: 900,
  японском: 400,
  китайском: 400,
  корейском: 400,
};

/** Язык вне списка читается по русской мерке: она из двух общих медленнее. */
export const DEFAULT_CHARS_PER_MINUTE = 960;

/**
 * Поправка на сложность, по делениям ползунка от 1 до 5.
 *
 * «С нуля» — короткие предложения и развёрнутые термины: те же знаки идут
 * быстрее. «Как специалисту» — термины, версии и имена API без пояснений:
 * знаков меньше, а времени на них больше. Разброс в четверть между краями
 * шкалы — тоже ручка, а не измерение.
 */
const DENSITY = [1.15, 1.07, 1, 0.94, 0.88];

/** Знаков в минуту с поправкой на то, как написан текст этого читателя. */
export function charsPerMinute(voice: Voice): number {
  const base = CHARS_PER_MINUTE[voice.language] ?? DEFAULT_CHARS_PER_MINUTE;
  const level = Math.min(5, Math.max(1, Math.round(
    Number.isFinite(voice.complexity) ? voice.complexity : DEFAULT_COMPLEXITY,
  )));
  return base * DENSITY[level - 1];
}

/**
 * Минуты дробные и не округляются здесь намеренно: округлённая карточка
 * — это полминуты ошибки, а их в выпуске сотня. Округляет только тот, кто
 * показывает число читателю.
 */
export const minutesOf = (chars: number, voice: Voice): number =>
  chars / charsPerMinute(voice);

/**
 * Длина карточки: заголовок и описание — всё, что читатель читает в ленте.
 *
 * Ровно та же сумма считается в SQL (`digestProgress`, `cardCharsOf`): там
 * её складывать дешевле, чем возить сотню описаний в память. Две формулы
 * одного числа разъезжаются молча, поэтому их равенство проверяется
 * на настоящем Postgres (`npm run verify:db`), а разделителей между полями
 * здесь нет — в SQL их пришлось бы приписывать руками на каждой строке.
 */
export const cardChars = (title: string, summary: string | null | undefined): number =>
  points(title) + points(summary ?? "");

/**
 * Знаки, а не единицы UTF-16. `.length` считает суррогатную пару за два,
 * а `char_length` в Postgres — за один: на эмодзи в заголовке две формулы
 * одного числа разъезжаются, и равенство, которое здесь объявлено, держалось
 * бы только на текстах без них.
 */
const points = (text: string): number => [...text].length;

export const digestMinutes = (
  cards: { title: string; summary: string | null }[],
  voice: Voice,
): number =>
  minutesOf(
    cards.reduce((chars, card) => chars + cardChars(card.title, card.summary), 0),
    voice,
  );

/**
 * Длина карточки, когда своих мерить ещё нечего: медиана по двумстам
 * описаниям живых выпусков (заголовок и описание вместе, 21 сентября 2026).
 * Нужна ровно один раз — у нового читателя, у которого выпусков ещё нет;
 * дальше меркой служит его собственный прошлый месяц.
 */
export const CARD_CHARS = 460;

/**
 * Сколько минут занимает одна карточка этого читателя.
 *
 * Мерка для перевода заказа в число мест: сама карточка пишется после
 * отбора, и заранее её длину можно только оценить. Оценка берётся из уже
 * написанных описаний (`cardCharsOf`) — так она сама подстраивается и под
 * его язык, и под его сложность, ничего об этом не зная.
 */
export const cardMinutes = (perCardChars: number, voice: Voice): number =>
  minutesOf(perCardChars > 0 ? perCardChars : CARD_CHARS, voice);

/**
 * Сколько карточек заказать отбору, чтобы вышло примерно `minutes`.
 *
 * Отбор умеет считать штуками: он делит места между темами, а место — это
 * материал. Одно число на входе, а не голос и знаки, — чтобы ровно та же
 * арифметика считалась в браузере, где полоса тем делит места: вторая копия
 * формулы разошлась бы с этой молча, и «3 из 40» означало бы не то, что придёт.
 *
 * Промах оценки ничего не ломает: время выпуска считается потом по настоящим
 * описаниям, и если вышло короче заказанного — это говорится вслух, а не
 * прячется добором слабого материала.
 */
export function itemsForMinutes(minutes: number, perCard: number, maxItems: number): number {
  return Math.max(0, Math.min(maxItems, Math.round(minutes / perCard)));
}

/**
 * «≈19 мин».
 *
 * Волна — часть обещания, а не украшение: время считается по нашей мерке
 * скорости, а читают все по-разному. Ровное «19 минут» обещало бы точность,
 * которой здесь нет ни у кого.
 *
 * Меньше минуты не показывается нулём: выпуск, о котором написано «≈0 мин»,
 * выглядит пустым, хотя в нём есть что читать.
 */
export const formatMinutes = (minutes: number): string =>
  `≈${Math.max(1, Math.round(minutes))} мин`;

/** Та же волна, но словом: в Telegram и в подписях «мин» читается обрубком. */
export const formatMinutesLong = (minutes: number): string => {
  const n = Math.max(1, Math.round(minutes));
  return `≈${n} ${plural(n, "минута", "минуты", "минут")}`;
};

/**
 * Недобор называется вслух, начиная с целой минуты.
 *
 * Меньшая разница — это разброс самой мерки, а не пустой день: сообщать
 * «19 из 20» значит извиняться за точность, которой мы не обещали.
 * Тревога, загорающаяся каждый день, ничем не отличается от выключенной.
 */
export const SHORTFALL_MIN = 1;

export const isShort = (minutes: number, target: number): boolean =>
  target - minutes >= SHORTFALL_MIN;

/**
 * Как о недоборе говорят читателю. Одна формулировка на ленту и на бота:
 * розданная по местам, она правится в одном и остаётся прежней в другом —
 * и два экрана обещают разное про один и тот же выпуск.
 */
export const shortfallNote = (minutes: number, target: number): string =>
  `${formatMinutesLong(minutes)} из ${target} — сегодня больше действительно важного нет`;
