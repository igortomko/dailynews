/** Apply to rendered text, never to URLs or stored source evidence. */
export function typography(value: string): string {
  return value
    /*
     * Короткое слово не остаётся висеть в конце строки.
     *
     * Было списком русских предлогов, и список отвечал только за русский:
     * латинские «a», «is», «of», «to» не совпадают с кириллическими даже
     * там, где выглядят одинаково. Замер на двухстах живых выпусках: из
     * 2896 коротких слов список не склеивал 811, и первая дюжина пропусков
     * — английская. Выпуск переводится на пятнадцать языков, и держать
     * список для каждого значит завести четырнадцать мест, где о новом
     * языке забудут молча.
     *
     * Поэтому мера — длина слова, а не словарь: одна и две буквы в любой
     * письменности. Трёхбуквенные предлоги остались перечнем: три буквы
     * общим правилом задели бы «дом», «код» и «год».
     *
     * Апостроф в запрете слева — из-за притяжательных: в «Anthropic's model»
     * иначе склеивается «s» с «model», то есть разрыв запрещается ровно там,
     * где он единственно и уместен.
     */
    .replace(/(?<![\p{L}\p{N}'\u2019])(для|при|без|над|под|\p{L}{1,2}) +(?=\S)/giu, "$1\u00a0")
    .replace(/(\d)[ ]+(?=\d{3}(?:\D|$))/gu, "$1\u00a0")
    .replace(/(\d)[ ]+(?=(?:%|₽|€|\$|км|мин|сек|с|кг|мг|г|млн|тыс|лет|год(?:а)?|час|января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)(?!\p{L}))/giu, "$1\u00a0")
    .replace(/([≈№$€]) +(?=\S)/gu, "$1\u00a0")
    .replace(/\b\d{4}-\d{2}-\d{2}\b|(?<![\p{L}\p{N}_.])(\d+(?:[.,]\d+)?)[ ]*[–—-][ ]*(\d+(?:[.,]\d+)?)(?![\p{L}\p{N}_.])/gu,
      (match, from: string | undefined, to: string | undefined) => from && to ? `${from}\u2060–\u2060${to}` : match)
    .replace(/(Шаг|Этап) +(\d)/gu, "$1\u00a0$2")
    .replace(/(\d) +(из) +(\d)/gu, "$1\u00a0$2\u00a0$3");
}
export function summaryTime(
  seconds: number,
  labels: { summaryMinute: string; summarySecond: string },
): string {
  const rounded = Math.max(10, Math.ceil(seconds / 10) * 10);
  const minutes = Math.floor(rounded / 60);
  const rest = rounded % 60;
  return `${minutes ? `${minutes}\u00a0${labels.summaryMinute}` : ""}${minutes && rest ? " " : ""}${rest ? `${rest}\u00a0${labels.summarySecond}` : ""}`;
}
