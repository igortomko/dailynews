/**
 * Тарифы и их пределы.
 *
 * Пределы стоят здесь, а не в базе: это продуктовое решение, а не настройка
 * читателя, и таблица из трёх строк, меняющаяся раз в квартал, стоила бы
 * миграции на каждую правку цены.
 *
 * Считать пределы умеет и интерфейс, и конвейер — и оба обязаны считать
 * одинаково. Понижение тарифа не выключает лишние источники задним числом:
 * они остаются в наборе читателя, и только прогон решает, кого опрашивать.
 * Поэтому предел применяется в двух местах, а живёт в одном.
 */
import type { Source } from "./types";

export const PLAN_IDS = ["free", "plus", "pro"] as const;
export type PlanId = (typeof PLAN_IDS)[number];

/**
 * Разделы настроек, которые тариф может закрыть.
 *
 * Список короткий намеренно. Закрывать имеет смысл то, что стоит денег:
 * лишний источник и лишняя сотня описаний — это счёт за модель. Язык,
 * сложность и манера не стоят ничего: тот же вызов, другой промпт, —
 * и держать их за тарифом значит ухудшать бесплатный выпуск без причины,
 * ради ощущения, что платное что-то даёт.
 *
 * `language` здесь и стоял — вопреки этому же абзацу, — и цена ошибки
 * оказалась не в деньгах. `effectiveVoice` подставлял в промпт «на языке
 * источника»: тот же вызов, те же 527 токенов входа и 338 выхода, ноль
 * экономии. Зато предел означал разное у разных людей: стартовый набор
 * почти весь англоязычный, и англичанину «язык источника» — его язык,
 * а русскому приходила английская лента, то есть продукт, которого он
 * не увидел ни разу. Это не тариф, а лотерея по языку. Продавать Plus
 * есть чем и без перевода: каждый день вместо через день, сорок
 * источников против пяти, двадцать минут против пяти, читалка.
 */
export const GATED = ["delivery", "posts"] as const;
export type Gated = (typeof GATED)[number];

export type Plan = {
  id: PlanId;
  /**
   * Имя тарифа. Живёт здесь, а не только в словаре: половина продукта
   * (форма источников, мастер интересов, серверные действия) ещё не читает
   * язык читателя и подписывает отказы этим именем напрямую. Экраны,
   * подключённые к словарю, берут перевод из `t.plans.label[id]` — он
   * совпадает с этим значением по-русски и расходится только на «free»
   * («Бесплатный» → «Free»), см. `src/lib/i18n/en|ru/plans.ts`.
   */
  label: string;
  /** $ в месяц. Ноль — бесплатный тариф. */
  price: number;
  /** Сколько источников опрашивается. Остальные включённые просто ждут. */
  maxSources: number;
  /**
   * Сколько интересов живёт одновременно.
   *
   * Персонален только предел, а цена — общая: темы всех читателей уходят
   * в вопрос Jev одним списком, и каждая удлиняет его на каждом материале
   * потока. Пятикратный рост предела сам по себе ничего не стоит, а вот
   * три сотни заведённых тем — это уже $2.8 в месяц на всех.
   */
  maxTopics: number;
  /**
   * Сколько минут чтения помещается в выпуск. Это и есть обещание тарифа:
   * читатель покупает время, за которое поймёт главное, а не число карточек.
   */
  maxMinutes: number;
  /**
   * Технический потолок: сколько карточек прогон напишет максимум.
   *
   * Не обещание, а предохранитель. Минуты переводятся в штуки оценкой
   * (`itemsForMinutes`), и промахнувшаяся оценка без этого числа означала бы
   * счёт за модель, которого никто не заказывал. В сравнении тарифов он
   * стоит мелким шрифтом под таблицей — там, где ему и место.
   */
  maxItems: number;
  /**
   * Сколько карточек выпуска пишутся разбором со сверкой (rich), а не
   * заголовком и описанием. Замер 22 сентября 2026: rich стоит $0.0080
   * против $0.00031 у обычной — в двадцать шесть раз дороже, потому что
   * статья читается целиком, разбирается на утверждения и сверяется
   * с источником. Весь выпуск разбором не вписывается ни в один тариф:
   * шестнадцать rich на Plus — это $3.29 в месяц при цене $3.99.
   */
  richCards: number;
  /** Виды источников, разрешённые тарифом. X платный, поэтому только Pro. */
  kinds: Source["kind"][];
  /** Разделы настроек, открытые тарифом. */
  sections: Gated[];
  /**
   * Сколько секунд озвучки в день. Ноль — озвучки на тарифе нет.
   *
   * В секундах, а не в статьях: счёт приходит за время звучания, и час
   * английского стоит вдвое дороже часа русского только потому, что
   * в него влезает вдвое больше знаков. Квота в статьях дотировала бы
   * один язык за счёт другого и молча.
   *
   * 2700 — это 45 минут. При $0.60 за час официального Azure выходит
   * $13.50 в месяц на читателя, если выбирать квоту каждый день; на Edge
   * TTS — ноль. Замеры и цены движков: docs/economics.md.
   */
  audioSecondsPerDay: number;
  /**
   * Через сколько дней приходит выпуск. Единица — каждую ночь.
   *
   * Это честнее, чем урезать размер выпуска: на бесплатном лента остаётся
   * такой же, просто реже. Урезанный выпуск выглядит как плохой продукт,
   * редкий — как бесплатный.
   */
  everyDays: number;
};

