/**
 * Незнакомое значение читается как бесплатный тариф, а не как Pro.
 * Опечатка в колонке не должна открывать платный источник (урок 0014:
 * код знает свои варианты сам и откатывается к безопасному).
 */
export function planOf(id: string | null | undefined): Plan {
  return PLANS[(id ?? "") as PlanId] ?? PLANS.free;
}

/**
 * Слова отказа: чем заменить `KIND_NAME`/`.label` и как собрать фразу.
 * Форма — ровно то, что несёт `plans` из словаря (`src/lib/i18n/en|ru/plans.ts`),
 * но описана здесь своим типом, а не импортом словаря: `lib/plans.ts` считает
 * пределы и правила, а от какого языка ждать текст — решает вызывающий,
 * а не эта зависимость.
 */
type DenialText = {
  kindName: Record<Source["kind"], string>;
  label: Record<PlanId, string>;
  // Список тарифов приходит списком, а склеивает его словарь. Склейка
  // здесь была русской — `join("», «")`, — и по-английски давала
  // «is only on the Plus», «Pro plan». Разделитель — такое же слово,
  // как остальная фраза, и жить ему там же, где она.
  kindOnlyOn: (kind: string, planNames: string[]) => string;
  kindUnavailable: (kind: string) => string;
};

/**
 * Почему этот вид источника тарифу не положен, или null, если положен.
 *
 * Отдельной функцией, потому что спросить надо дважды и в разных местах:
 * при сохранении и до разбора ссылки. X — платный, у него счёт
 * за прочитанные посты, и разбор сам по себе уже стоит денег.
 *
 * Третий параметр — словарь, и он обязателен. Принимает готовые слова,
 * а не отдаёт ключ отказа: вызывающему (`sources.ts`, `actions.ts`) нужна
 * готовая строка для тоста, а ключ переложил бы сборку фразы на каждый
 * вызов — там, где сейчас достаточно прочитать результат. Русские слова
 * по умолчанию тут стояли и ровно один вызов их и получил: `discoverSource`
 * отказывал по-русски читателю с английским интерфейсом. Отказ на чужом
 * языке — это отказ, который выглядит как успех сборки.
 */
export function kindDenial(plan: Plan, kind: Source["kind"], t: DenialText): string | null {
  if (plan.kinds.includes(kind)) return null;
  const where = PLAN_IDS.filter((id) => PLANS[id].kinds.includes(kind)).map((id) => t.label[id]);
  return where.length
    ? t.kindOnlyOn(t.kindName[kind], where)
    : t.kindUnavailable(t.kindName[kind]);
}

/**
 * Что можно заказать. Список один на все тарифы, за чужими значениями —
 * корона: спрятанный вариант никогда не показывает, за что предлагают
 * платить. Верхнее значение совпадает с потолком Pro — корона, за которой
 * нет тарифа, ведёт в никуда.
 */
export const READING_MINUTES = [5, 10, 20, 30, PLANS.pro.maxMinutes];

/**
 * Ниже этого заказ не опускается. Совпадает с нижней границей ограничения
 * колонки `digest_minutes`, а не с первым значением списка: перенос из штук
 * мог дать четыре минуты, и такое значение остаётся своим вариантом, пока
 * его не сменили. Прижми его к пятёрке — и выбранный вариант молча
 * подменялся бы соседним, а вернуться к своему было бы нечем.
 */
export const MIN_READING_MINUTES = 3;

/**
 * Сколько минут реально придёт: заказанное читателем, прижатое потолком
 * тарифа. Понижение тарифа не трогает `digest_minutes` в базе, и сохранённые
 * сорок пять переживают там переход на бесплатный.
 *
 * Одной функцией, потому что считать это надо в трёх местах — в прогоне,
 * в догрузке и на странице «О проекте», — и три копии одного `Math.min`
 * разойдутся молча ровно так же, как таблица тарифов, переписанная руками.
 */
export const minutesCap = (minutes: number, plan: Plan) =>
  Math.min(minutes, plan.maxMinutes);

/**
 * Сколько времени выпуск может отдать на самом деле: заказ, прижатый обоими
 * потолками тарифа — по времени и по числу карточек.
 *
 * Второй потолок нужен здесь, а не только в отборе. Карточки у читателя
 * бывают короче медианы (свой язык, своя сложность), и тогда сорок штук
 * на Plus — это не двадцать минут, а семнадцать. Сравнивай набранное
 * с необрезанным заказом — и строка «сегодня больше действительно важного
 * нет» горела бы у него каждый день, объясняя наш собственный предел
 * тишиной в потоке. Тревога, горящая всегда, ничем не отличается
 * от выключенной.
 */
export const targetMinutes = (minutes: number, plan: Plan, perCard: number) =>
  Math.min(minutesCap(minutes, plan), plan.maxItems * perCard);

export const allows = (plan: Plan, section: Gated) => plan.sections.includes(section);

/** Самый дешёвый тариф, который открывает раздел. Для подписи в заглушке. */
export const cheapestWith = (section: Gated): Plan =>
  PLAN_IDS.map((id) => PLANS[id]).find((plan) => allows(plan, section)) ?? PLANS.pro;

/**
 * Что именно закрыто тарифом — описано данными, а не разложено по экранам.
 *
 * `has` — та же проверка, по которой возможность работает. Корона, текст
 * окна и настоящий предел обязаны опираться на одно правило: корона над
 * работающей кнопкой и работающая кнопка без короны — одинаково стыдно,
 * и оба случая на глаз незаметны.
 */
export type FeatureId =
  | "personalization" | "delivery" | "x" | "posts"
  | "topics" | "digest" | "sources" | "cadence" | "audio" | "rich";

export type Feature = {
  has: (plan: Plan) => boolean;
};

export const FEATURES: Record<FeatureId, Feature> = {
  // Название и описание каждой возможности живут в словаре
  // (`t.plans.feature[id]` из `src/lib/i18n/en|ru/plans.ts`), а не здесь: это
  // подпись для читателя, а не правило. Здесь остаётся только `has` —
  // проверка, по которой корона и настоящий предел обязаны совпадать.
  personalization: {
    // Доступна всем: промпт от неё не дорожает ни на токен. Перевод сюда же
    // и входит — своей записи у него нет намеренно. Возможность, которая
    // есть у всех, не нуждается ни в короне, ни в окне с предложением:
    // окно открылось бы пустым, потому что предлагать нечего.
    has: () => true,
  },
  delivery: {
    has: (plan) => allows(plan, "delivery"),
  },
  rich: {
    // Разбор — количественная возможность, как озвучка: у Plus две карточки,
    // у Pro десять. Корона ставится по тому же правилу, по которому работает
    // предел, иначе она обещает не то.
    has: (plan) => plan.richCards > 0,
  },
  posts: {
    has: (plan) => allows(plan, "posts"),
  },
  x: {
    has: (plan) => plan.kinds.includes("x"),
  },
  topics: {
    has: (plan) => plan.maxTopics > PLANS.free.maxTopics,
  },
  cadence: {
    has: (plan) => plan.everyDays <= 1,
  },
  digest: {
    has: (plan) => plan.maxMinutes > PLANS.free.maxMinutes,
  },
  audio: {
    // Та же проверка, по которой работает предел: корона над работающей
    // кнопкой и работающая кнопка без короны одинаково незаметны на глаз
    // и одинаково врут.
    has: (plan) => plan.audioSecondsPerDay > 0,
  },
  sources: {
    has: (plan) => plan.maxSources > PLANS.free.maxSources,
  },
};

/**
 * Выпуск этой ночью или нет.
 *
 * День считается от даты, а не от прошлого выпуска: прогон могут запустить
 * дважды за сутки или пропустить ночь, и отсчёт «от прошлого раза» тогда
 * съезжает навсегда. Номер читателя в формуле разносит бесплатных по разным
 * ночам — иначе половина ленты просыпается в один день.
 */
export function issuesToday(plan: Plan, readerId: number, day: string | Date): boolean {
  if (plan.everyDays <= 1) return true;
  const epochDay = Math.floor(new Date(day).getTime() / 86_400_000);
  return (epochDay + readerId) % plan.everyDays === 0;
}

/** Самый дешёвый тариф, на котором возможность есть. */
export const cheapestFor = (id: FeatureId): Plan =>
  PLAN_IDS.map((planId) => PLANS[planId]).find((plan) => FEATURES[id].has(plan)) ?? PLANS.pro;

/**
 * Что из выбранного читателем опрашивать в этом прогоне.
 *
 * На вход идёт его собственный набор (`readerSources`), а не каталог:
 * каталог общий, чтобы один фид опрашивался один раз на всех, но чей это
 * выпуск — решает личный выбор.
 *
 * Порядок — по id: при понижении тарифа остаются те, что заведены раньше,
 * и набор не пляшет от прогона к прогону. Запрещённый вид отсекается до
 * предела по числу, иначе три ленты X на бесплатном тарифе съедали бы
 * места живых источников, ничего при этом не собирая.
 */
export function sourcesForPlan(sources: Source[], plan: Plan): Source[] {
  return sources
    .filter((source) => plan.kinds.includes(source.kind))
    .sort((a, b) => a.id - b.id)
    .slice(0, plan.maxSources);
}

/**
 * С какого момента работает оплата. `null` — подписка скрыта, и у всех Pro.
 *
 * Константа в коде, а не переменная окружения: тариф считают и веб,
 * и прогон в Actions, а окружения у них разные — переменная, заданная
 * в одном месте и забытая в другом, дала бы Pro в ленте и Free в выпуске.
 * Включается правкой этой строки на дату (ISO) и развёртыванием; дату
 * можно поставить в будущее, и оплата включится сама.
 */
export const BILLING_FROM: string | null = null;

/**
 * Действующая дата включения. Проверки (`npm test`, `npm run verify:db`)
 * меряют пределы тарифов, а при выключенной оплате пределов нет ни у кого:
 * они включают её у себя в процессе переменной `BILLING_FROM_FOR_CHECKS`.
 * Читается на каждый вызов, а не при импорте: проверка ставит её после
 * того, как модули уже загружены. В браузере `process.env` пуст — там
 * решает константа.
 */
export const billingFrom = (): string | null =>
  (typeof process !== "undefined" && process.env.BILLING_FROM_FOR_CHECKS) || BILLING_FROM;

/**
 * Сколько дней ранний читатель остаётся на Pro после включения оплаты.
 * Без этого в день включения у всех гасло бы то, чем они пользовались,
 * и узнавали бы они об этом по пропавшей кнопке, а не из сообщения.
 */
export const FOUNDER_GRACE_DAYS = 30;

/**
 * Скидка ранним, процентов — навсегда, пока подписка не отменена.
 * Число здесь только для текста: сама скидка — код в Paddle
 * (`type: percentage`, `recur: true` без предела периодов), его имя лежит
 * в `PADDLE_DISCOUNT_FOUNDER`, и окно оплаты подставляет его само.
 *
 * Тридцать, а не пятьдесят, — расчёт 23 сентября 2026: при 5% + $0.50
 * комиссии Pro за $4.99 оставлял $0.25–1.25 с активного читателя
 * (десять разборов в день — $2.4 в месяц), а $6.99 оставляет $2–3.
 */
export const FOUNDER_DISCOUNT = 30;

export const billingOn = (now = new Date(), from: string | null = billingFrom()): boolean =>
  from !== null && now >= new Date(from);

/**
 * Пришёл до включения оплаты. Пока оплата не включена, ранние — все.
 * Непрочитанная дата — не ранний: скидка и лишний месяц Pro не должны
 * доставаться по ошибке разбора.
 */
export function isFounder(createdAt: string | null | undefined, from: string | null = billingFrom()): boolean {
  if (from === null) return true;
  const at = new Date(createdAt ?? "").getTime();
  return Number.isFinite(at) && at < new Date(from).getTime();
}

/** Докуда ранний читатель на Pro после включения. `null` — оплата не включена. */
export const founderGraceEnds = (from: string | null = billingFrom()): Date | null =>
  from === null ? null : new Date(new Date(from).getTime() + FOUNDER_GRACE_DAYS * 86_400_000);

/** За сколько дней до конца месяца Pro ранним напоминают в чате. */
export const FOUNDER_REMIND_DAYS = 3;

/**
 * Что сказать раннему в чате сегодня: что оплата включилась, что месяц Pro
 * кончается, или ничего.
 *
 * `lastSaidAt` — `readers.upsell_at`, отметка последней строки про тариф.
 * Раньше даты включения — о включении ещё не говорили. Раньше начала окна
 * напоминания — о конце ещё не говорили. Отдельные колонки под каждое
 * «уже сказали» не нужны: строки идут по порядку, и одной отметки хватает.
 * Спящий, вернувшийся за день до конца, получит «включилась» с датой —
 * напоминание ему уже ничего не добавит.
 */
export function founderNotice(
  createdAt: string | null | undefined,
  lastSaidAt: string | null | undefined,
  now = new Date(),
  from: string | null = billingFrom(),
): "started" | "ending" | null {
  const grace = founderGraceEnds(from);
  if (!from || !grace || !billingOn(now, from) || now >= grace || !isFounder(createdAt, from)) return null;
  const said = lastSaidAt ? new Date(lastSaidAt).getTime() : Number.NEGATIVE_INFINITY;
  if (!(said >= new Date(from).getTime())) return "started";
  const remindFrom = grace.getTime() - FOUNDER_REMIND_DAYS * 86_400_000;
  if (now.getTime() >= remindFrom && said < remindFrom) return "ending";
  return null;
}

/**
 * Цена со скидкой ранних, как её посчитает Paddle: до цента.
 * Считается отсюда, а не пишется в текст: цены тарифов живут в `PLANS`.
 */
export const founderPrice = (plan: Plan): number =>
  Math.round(plan.price * (100 - FOUNDER_DISCOUNT)) / 100;
