/**
 * Какая версия Jev отвечает — и что делать, когда она сменилась.
 *
 * Клиент SDK без настройки ходит в `jev-latest`, то есть в плавающую
 * версию. Для чат-модели это нормально, а здесь от неё зависят числа,
 * которые сравниваются между собой: порог дубля 0,6, ряды калибровки
 * по дням, корзины скора. Документация TypeSafe говорит об этом прямо —
 * пинуй версию, если от поведения модели зависят пороги, и записывай ту,
 * что вернулась.
 *
 * Записывать мы и так записываем (`model_calls.model`), а вот сказать
 * вслух было нечему: обновись Jev до 1.14 — скоринг продолжит работать,
 * выпуск придёт вовремя, и ни одна проверка не сработает. Числа при этом
 * станут несравнимыми с прошлыми ровно так же, как от переписанной
 * формулировки вопроса.
 *
 * Поэтому версия не пинуется намертво, а называется: пин остановил бы
 * обновления молча (и однажды у старой версии кончится поддержка),
 * а строка в логе говорит, с какого дня ряд сравнивать нельзя.
 */

/**
 * Версия, на которой замерены нынешние пороги и собраны нынешние ряды.
 * Меняется вместе с решением «числа до и после несравнимы» — как и
 * формулировки вопросов.
 */
export const JEV_BASELINE = process.env.TYPESAFE_MODEL?.trim() || "jev-1.13.0";

/**
 * Что сказать про ответившую версию, или null, если это та же самая.
 *
 * Строкой, а не исключением: смена версии — не поломка, и ронять из-за неё
 * выпуск значило бы наказывать читателя за чужой релиз.
 */
export function jevVersionNote(answered: string | null | undefined): string | null {
  const model = (answered ?? "").trim();
  if (!model || model === JEV_BASELINE) return null;
  return `Jev ответил ${model}, а пороги и ряды замерены на ${JEV_BASELINE}: ` +
    `числа с этого дня сравнивать с прошлыми нельзя. ` +
    `Сверить порог дубля и корзины калибровки, затем обновить TYPESAFE_MODEL.`;
}
