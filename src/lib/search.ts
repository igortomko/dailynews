/**
 * Словарь Postgres для поиска: один на все выпуски и на запрос.
 *
 * Словарь решает, сводятся ли словоформы: «цены» и «цена» — одно слово
 * только для того, чьим словарём разобран текст. Поэтому запрос обязан
 * разбираться тем же словарём, что и текст, — а текст с миграции 0046
 * лежит уже разобранным: хранимые tsvector в `digest_items` и `items`
 * считаются Postgres при записи, и generated column требует константы.
 * Считать вектор на каждый запрос стоило 50 мс на двухстах строках
 * и росло линейно — к девяноста дням архива около секунды на слово.
 *
 * Текст двуязычный: описание написано языком читателя, заголовок источника
 * почти всегда английский. Русская конфигурация разбирает латиницу тем же
 * английским стеммером, что и английская (замер: «prices» находит «price»,
 * «studies» — «study» в обеих), и сверх того сводит «цена» с «цены», чего
 * английская не может. Отсюда именно russian, а не `simple` и не `english`.
 *
 * Цена константы — португальский или испанский читатель, чьи словоформы
 * русский словарь не сведёт: точные формы найдутся, склонения — нет.
 * Такого читателя пока нет; появится — словарь на выпуск хранится колонкой
 * regconfig и уходит в выражение вектора вместо константы.
 */
export const SEARCH_CONFIG = "russian";

/**
 * Границы найденного внутри отрывка от `ts_headline`.
 *
 * Управляющие символы, а не `<b>`: отрывок собирается из описания и текста
 * статьи, и вставить туда разметку значит однажды отрисовать чужой
 * `<script>` как свой. Символы, которых в тексте не бывает, режутся
 * обратно на куски и уезжают в `<mark>` обычными строками.
 */
export const HL_START = "\u0001";
export const HL_END = "\u0002";

/**
 * Настройки отрывка. Один фрагмент, а не два: у двух отрывок перестаёт быть
 * куском текста и становится склейкой, а склейку уже не сравнить с началом
 * и концом описания — значит, многоточие по краям пришлось бы ставить
 * вслепую, в том числе там, где ничего не отрезано.
 */
export const HL_OPTIONS = `StartSel=${HL_START},StopSel=${HL_END},MaxFragments=1,MaxWords=32,MinWords=16`;

export type Part = { text: string; mark: boolean };

/** Отрывок, разложенный на обычный текст и найденное. */
export function highlight(text: string): Part[] {
  const parts: Part[] = [];
  let rest = text;
  while (rest.length > 0) {
    const open = rest.indexOf(HL_START);
    if (open === -1) {
      parts.push({ text: rest, mark: false });
      break;
    }
    if (open > 0) parts.push({ text: rest.slice(0, open), mark: false });
    const close = rest.indexOf(HL_END, open);
    // Смещения считаются по длине самих меток, а не единицей: метки
    // экспортируются, и первая же замена на что-нибудь длиннее символа
    // оставила бы её хвост в тексте карточки, ничего не сломав по дороге.
    const from = open + HL_START.length;
    // Незакрытая метка — это обрезанный отрывок. Остаток уходит обычным
    // текстом: подсветить «до конца строки» значит залить половину карточки.
    if (close === -1) {
      parts.push({ text: rest.slice(from), mark: false });
      break;
    }
    parts.push({ text: rest.slice(from, close), mark: true });
    rest = rest.slice(close + HL_END.length);
  }
  return parts;
}

/**
 * Тот же запрос, но «хотя бы одно слово», или null, если ослаблять нечего.
 *
 * Ищут вопросом, а не ключевыми словами: «где я видел про uranium
 * и дата-центры». Требование всех слов разом просит ровно того, чего
 * в тексте нет («видел»), и поиск отвечает «ничего не нашлось» на запрос,
 * ответ на который лежит в архиве. Поэтому вторым заходом слова связываются
 * через «или», а порядок выдачи сам поднимает наверх те материалы,
 * где сошлось больше слов.
 *
 * Слова соединяются оператором самого websearch, а не подменой «&» на «|»
 * в готовом tsquery: в запросе бывает «AT&T», и такая подмена ломает
 * не оператор, а само слово.
 */
export function anyOf(query: string): string | null {
  const words = query
    .trim()
    .split(/\s+/)
    // Слово под запретом в ослаблении не участвует вовсе. «уран
    // -обогащение» через «или» превращается в «уран ИЛИ НЕ обогащение»
    // и отвечает почти всем архивом — ровно обратное тому, что просили.
    .filter((word) => !word.startsWith("-"))
    // Кавычки уходят вместе с фразой: слова уже разделены пробелами,
    // и осиротевшая кавычка открывает фразу, которая ничем не кончается.
    .map((word) => word.replace(/"/g, ""))
    .filter(Boolean);
  return words.length > 1 ? words.join(" or ") : null;
}
