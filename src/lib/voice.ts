/**
 * Как написан текст дайджеста: сложность языка и манера.
 *
 * Здесь остаётся только `instruction` — то, что уходит в промпт модели,
 * и всегда по-русски независимо от языка интерфейса: это часть измеренного
 * промпта, а не текст, который читает человек. Подпись и подсказка переехали
 * в словарь интерфейса (src/lib/i18n/en/settings.ts и ru/settings.ts,
 * `voice.complexity` и `voice.styles`) — их язык обязан идти за языком интерфейса, а не
 * за языком выпуска, и держать их здесь означало бы английский интерфейс
 * с русской подписью на кнопке.
 *
 * `key` — общий якорь между инструкцией и подписью, и трогать его нельзя:
 * он лежит в `profile.style`, и переименование осиротит сохранённое.
 */
export type VoiceOption = {
  key: string;
  /** Требование, которое уходит в промпт дайджеста. */
  instruction: string;
};

