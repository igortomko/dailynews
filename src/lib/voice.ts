/**
 * Как написан текст дайджеста: сложность языка и манера.
 *
 * Подпись для читателя и требование к модели лежат рядом не для красоты.
 * Разведи их по разным файлам — и появится манера, которая есть в селекте,
 * но не доехала до промпта: селект работает, дайджест пишется, текст тот же
 * самый. Это ровно тот отказ, который выглядит как успех.
 */
export type VoiceOption = {
  key: string;
  /** Подпись в форме. */
  label: string;
  /** Строка под полем: что изменится в тексте. */
  hint: string;
  /**
   * Первые слова описания, написанного так. Показывается в карточке манеры:
   * «Нейтрально и без оценок» — это обещание, а «Компания выпустила новую
   * модель…» — то, что получится, и выбирают по нему.
   */
  example?: string;
  /** Требование, которое уходит в промпт дайджеста. */
  instruction: string;
};

