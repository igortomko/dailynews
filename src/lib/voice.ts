export const flagOf = (language: string): string => FLAGS[language] ?? "";

export const DEFAULT_COMPLEXITY = 3;
export const DEFAULT_STYLE = "нейтральный";

/** Как писать: язык, сложность, манера. */
export type Voice = { language: string; complexity: number; style: string };

export const DEFAULT_VOICE: Voice = {
  language: "русском",
  complexity: DEFAULT_COMPLEXITY,
  style: DEFAULT_STYLE,
};

/**
 * `level || DEFAULT` здесь нельзя: ноль — значение вне шкалы, и его надо
 * прижать к первому делению, а не подменить серединой. Тот же промах, что
 * с пустой строкой в настройках провайдера: `||` глотает законный ноль,
 * и текст тихо пишется не той сложности.
 */
export const complexityAt = (level: number): VoiceOption =>
  COMPLEXITY[
    Math.min(5, Math.max(1, Math.round(Number.isFinite(level) ? level : DEFAULT_COMPLEXITY))) - 1
  ];

/** Незнакомая манера читается как нейтральная: база не должна падать из-за нового пункта. */
export const styleOf = (key: string): VoiceOption =>
  STYLES.find((entry) => entry.key === key) ?? STYLES[0];
