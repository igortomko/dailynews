import type { Dict } from "@/lib/i18n";

export type TimeLabels = Dict["feed"]["time"];

/**
 * Пробелы Intl, приведённые к обычному.
 *
 * У Node и у браузера ICU разных версий, и они расходятся невидимо: узкий
 * неразрывный пробел (U+202F) перед «г.» Node ставит в `formatRange`,
 * а Chrome — нет. На вид строки одинаковы до символа, но React сверяет
 * байты: «19–22 сентября 2026 г.» с сервера и «19–22 сентября 2026 г.»
 * из браузера роняли гидрацию всей ленты, а в консоли стояли две строки,
 * отличить которые глазом нельзя.
 *
 * Правится здесь, а не у каждого вызова: дат в интерфейсе много, а обе
 * ICU обновляются молча и не в ногу.
 */
const stable = (text: string) => text.replace(/[\u202f\u2009\u00a0]/g, " ");

/**
 * «21 сентября 2026 г.» из «2026-09-21» на языке читателя. Полдень,
 * а не полночь: день выпуска — это день, а не момент, и полночь по UTC
 * в западном поясе уже вчера. Одна функция на шапку ленты и на обзор —
 * дата выпуска в двух местах обязана читаться одинаково.
 */
export const formatDay = (day: string, locale: string) =>
  stable(
    new Intl.DateTimeFormat(locale, { day: "numeric", month: "long", year: "numeric" }).format(
      new Date(`${day}T12:00:00`),
    ),
  );

/**
 * «18–22 сент. 2026 г.» — окно из нескольких дней в шапке ленты.
 *
 * `formatRange` самого Intl, а не две даты через тире: он сам решает,
 * что в паре повторяется, и не пишет месяц и год дважды. Собранная руками
 * строка была бы верной по-русски и разъехалась бы в первом же языке,
 * где порядок частей другой.
 *
 * Месяц короткий и года нет, в отличие от `formatDay`, и это про ширину
 * шапки, а не про вкус: на телефоне под дату остаётся около семидесяти
 * пикселей, и «19–22 сентября 2026 г.» разваливалось на три строки,
 * выдавливая кнопки из отведённой шапке высоты.
 *
 * Год не выброшен, а отдан Intl: он дописывает его сам, когда без него
 * непонятно («30 дек. 2025 г. – 2 янв. 2026 г.»). Окно живёт неделю
 * и почти всегда лежит внутри одного года — там год ничего не различает,
 * а на границе лет различает, и тогда он появляется.
 *
 * Окно в один день сюда не приходит — его пишет `formatDay`; но если
 * придёт, `formatRange` отдаст обычную дату, а не «22–22».
 */
export const formatDayRange = (from: string, to: string, locale: string) =>
  stable(
    new Intl.DateTimeFormat(locale, { day: "numeric", month: "short" }).formatRange(
      new Date(`${from}T12:00:00`),
      new Date(`${to}T12:00:00`),
    ),
  );

/**
 * «10ч» вместо «10 часов назад». В строке метаданных время стоит рядом
 * с источником и темой, и развёрнутая форма занимает там больше места,
 * чем несёт смысла: «назад» не добавляет ничего, а читается в каждой
 * карточке заново.
 *
 * Словарь обязателен, и это не придирка к сигнатуре. Русский по умолчанию
 * прожил ровно до первого английского читателя: забытый аргумент отдавал
 * «10ч» посреди английского интерфейса — ни ошибки, ни предупреждения,
 * заметить нечем иначе как глазами на проде. Обязательный параметр
 * переносит это в сборку, где такую забывчивость видно бесплатно.
 */
export function relativeTime(value: string | Date, t: TimeLabels): string {
  const then = typeof value === "string" ? new Date(`${value}${value.length === 10 ? "T12:00:00" : ""}`) : value;
  if (Number.isNaN(then.getTime())) return "";

  const minutes = Math.round((Date.now() - then.getTime()) / 60_000);
  if (minutes < 1) return t.now;
  if (minutes < 60) return t.minutesAgo(minutes);

  const hours = Math.round(minutes / 60);
  if (hours < 24) return t.hoursAgo(hours);

  const days = Math.round(hours / 24);
  if (days < 7) return t.daysAgo(days);

  return t.monthDay(then);
}
