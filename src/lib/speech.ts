/**
 * Как текст звучит, а не как он написан.
 *
 * Русский голос читает латиницу по русским правилам: `Gemini` становится
 * «Джимр Найв Майя», `Qwen 3.5` — «KORN 3.5», `x-High` — «HIG». Замерено
 * на живых описаниях: английские названия стоят в каждом втором заголовке
 * этой ленты, так что это не угол, а середина.
 *
 * Разметить произношение тегами нельзя, и это ограничение сервиса, а не
 * библиотеки: эндпоинт Edge принимает только `speak`, `voice` и `prosody`,
 * а `<lang>`, `<phoneme>`, `<sub>`, `<emphasis>` и `<break/>` отбивает все
 * до одного — проверено контрольным прогоном, где тот же текст без тегов
 * прошёл. Поэтому произношение подставляется в сам текст.
 *
 * Подстановка живёт здесь, а не в отправке: движок однажды сменится
 * (официальный Azure, Gemini), а у другого движка другая нужда — кому-то
 * нужна кириллица, кому-то теги. Смысл — «вот этот кусок латинский» —
 * один на всех, форма разная. Разведи их по файлам, и появится термин,
 * который размечен, но не доехал до озвучки.
 */

/**
 * Латинский кусок: начинается буквой, дальше буквы и цифры, и через
 * `-`, `.` или `+` к нему клеятся такие же куски.
 *
 * Дефис клеит только латиницу с латиницей: в `SPL-токеном` кусок — это
 * `SPL`, а не `SPL-токеном`, потому что за дефисом кириллица, и правило
 * до неё не дотягивается. Иначе в словарь уехало бы по строке на каждый
 * падеж русского хвоста.
 */
const RUN = /[A-Za-z][A-Za-z0-9]*(?:[-.+][A-Za-z0-9]+)*/g;

/**
 * Английские буквы по буквам — для аббревиатур вроде `VHDL`.
 *
 * Ряд на язык, а не один на всех: `GPU` по-русски «джи-пи-ю», по-украински
 * «джі-пі-ю», а по-японски ジーピーユー. Общий ряд отдал бы японцу кириллицу —
 * вовремя, без ошибки и совершенно не ту.
 */
const LETTERS: Record<string, Record<string, string>> = {
  "русском": {
    a: "эй", b: "би", c: "си", d: "ди", e: "и", f: "эф", g: "джи",
    h: "эйч", i: "ай", j: "джей", k: "кей", l: "эль", m: "эм", n: "эн",
    o: "оу", p: "пи", q: "кью", r: "ар", s: "эс", t: "ти", u: "ю",
    v: "ви", w: "дабл-ю", x: "экс", y: "уай", z: "зед",
  },
  "украинском": {
    a: "ей", b: "бі", c: "сі", d: "ді", e: "і", f: "еф", g: "джі",
    h: "ейч", i: "ай", j: "джей", k: "кей", l: "ел", m: "ем", n: "ен",
    o: "оу", p: "пі", q: "к'ю", r: "ар", s: "ес", t: "ті", u: "ю",
    v: "ві", w: "дабл-ю", x: "екс", y: "уай", z: "зед",
  },
};

/**
 * Сокращения, у которых движок читает точку как конец предложения.
 *
 * «Раунд закрыт на 50 тыс. долларов» звучит с провалом в 1,3 секунды
 * ровно на сокращении: движок обрывает фразу и начинает следующую.
 * Замер тем же голосом: с точкой 5,76 с, без неё 4,42 с, — и без точки
 * фраза звучит той же речью, что написанная словом («400 тыс тонн» против
 * «400 тысяч тонн» — остаток 0,07 от энергии сигнала, то есть тот же звук).
 *
 * Список, а не правило «точка не в конце предложения — снять». Правило
 * проверено и отвергнуто на том же голосе: `2025 г.` он читает как
 * «две тысячи двадцать пятый год» (остаток 0,05 к явно написанному «год»),
 * а `2025 г` без точки — уже не «год», не «года», не «грамм» и не «гэ»
 * (остаток 1,15–1,34 к каждому). Снятие точки чинит сломанное и ломает
 * работавшее, и на слух второе неотличимо от первого.
 *
 * Ряд на язык, как у названий букв и затравки: `тыс.` — русское
 * сокращение, и немецкому голосу подставлять нечего. Новая строка
 * заводится замером, а не догадкой: синтезировать фразу с точкой и без,
 * сравнить длину — лишняя секунда тишины видна в байтах.
 */
const CLIPPED: Record<string, string[]> = {
  "русском": ["тыс"],
};

/**
 * Снять точку там, где она не конец предложения, а хвост сокращения.
 *
 * Граница слова — «рядом нет буквы, цифры и подчёркивания», а не `\b`:
 * тот знает только латиницу (урок из `lexicon.ts`). Точка снимается
 * только перед пробелом: `на 50 тыс.` в конце текста — это и есть конец,
 * и пауза там по делу.
 */
export function unabbreviate(text: string, language: string): string {
  const words = CLIPPED[language];
  if (!words) return text;
  return text.replace(
    new RegExp(`(^|[^\\p{L}\\p{N}_])(${words.join("|")})\\.(?=\\s)`, "giu"),
    "$1$2",
  );
}

/**
 * Затравка словаря: то, что встречается в этой ленте каждый день, и то,
 * где машина ошибётся предсказуемо.
 *
 * Это не механизм, а несколько строк, чтобы первый же выпуск не пошёл
 * в модель за `Google`. Всё остальное копится в базе по мере встречи.
 *
 * Затравка тоже по языку: «джемини» — русское произношение, и подставить
 * его японскому читателю значит выдать кириллицу за перевод. Для языка,
 * которого здесь нет, затравки просто нет — всё уедет в модель и осядет
 * в базе, то есть дороже на один вопрос, а не неправильно.
 */
