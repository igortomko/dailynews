export const voiceFor = (language: string): string | null => VOICES[language] ?? null;

/**
 * Локаль даты — из того же голоса, которым выпуск читают.
 *
 * Второго списка «язык → локаль» здесь нет намеренно: он разъехался бы
 * с голосами молча, и выпуск, прочитанный немецким голосом, назвал бы
 * число по-русски — вовремя, без ошибки и не тем языком. Голоса Edge
 * называются `xx-YY-ИмяNeural`, и локаль — это первые две части.
 */
export const localeOfVoice = (voice: string): string => voice.split("-").slice(0, 2).join("-");

/**
 * Вступление подкаста: что это и за какое число.
 *
 * Открытый через день файл в списке Telegram неотличим от вчерашнего —
 * поэтому первым звучит имя продукта и дата. Дата собирается `Intl`
 * по локали голоса, а не строкой из словаря интерфейса: словарей два
 * (русский и английский), языков выпуска пятнадцать, и фраза из словаря
 * однажды прозвучала бы по-русски немецким голосом. `Intl` знает все
 * пятнадцать и ставит и порядок, и падеж, и цифры своей письменности.
 *
 * Сколько внутри новостей, вступление не называет: число живо только
 * в паре с существительным, а «новость / новости / новостей» — это
 * правила множественного числа пятнадцати языков, которых мы не знаем
 * и проверить не можем. Сколько их, и так написано в заголовке файла.
 *
 * Год не называется: этот файл слушают назавтра, а не через год.
 *
 * Запятая, а не точка. Точка после имени — это конец предложения, и движок
 * держит на ней 1,13 секунды: «Reporta» повисает, дата приходит отдельной
 * фразой, и вступление из двух слов растягивается с 3,3 до 4,4 секунды.
 * Та же точка, что в «50 тыс.», и тот же замер.
 */
export function podcastIntro(day: string, voice: string): string {
  // Полдень UTC, а не полночь: день приходит строкой `ГГГГ-ММ-ДД`,
  // и любой сдвиг пояса в разборе увёл бы дату на соседнюю.
  const date = new Intl.DateTimeFormat(localeOfVoice(voice), {
    day: "numeric",
    month: "long",
    timeZone: "UTC",
  }).format(new Date(`${day}T12:00:00Z`));
  return `Reporta, ${date}.`;
}

/**
 * Голос, когда читатель просил не переводить.
 *
 * Язык оригинала мы не знаем — в `items` его нет, и выяснять его отдельным
 * вызовом ради выбора голоса дороже, чем посмотреть на буквы.
 * ponytail: две ветки по письменности; понадобится третья — брать
 * определитель языка, а не дописывать условия.
 */
export function voiceForText(text: string): string {
  const cyrillic = (text.match(/[а-яё]/gi) ?? []).length;
  return cyrillic > text.length / 10 ? VOICES["русском"] : VOICES["английском"];
}

/**
 * Почему озвучить нельзя. Пустая строка — можно.
 *
 * Чистая функция и отдельно от отправки, как `articleBlocker` у читалки:
 * предел применяется трижды — форма гасит кнопку, серверное действие
 * повторяет проверку, а конвейер решает сам, — и правило при этом живёт
 * в одном месте. Серверное действие зовётся по своему адресу мимо
 * страницы, так что гашения кнопки недостаточно.
 */
export function audioBlocker(
  reader: { telegram_id: string | number | null },
  plan: { audioSecondsPerDay: number },
  secondsToday: number,
  wantSeconds: number,
  t: AudioErrors,
  planLabel: string,
): string {
  // Ни одно из чисел здесь не написано руками: подпись берёт ту же
  // `audioSecondsPerDay`, по которой работает предел. Разойдись они —
  // читателю назвали бы одну квоту, а применили другую, и оба числа
  // выглядели бы одинаково правдоподобно.
  if (plan.audioSecondsPerDay <= 0) return t.audioOnPro(planLabel);
  // Слушать нечем: озвучка уходит в Telegram, другого плеера у неё нет.
  if (!reader.telegram_id) return t.audioNoTelegram;
  const left = plan.audioSecondsPerDay - secondsToday;
  if (left <= 0) return t.audioCapReached(Math.floor(plan.audioSecondsPerDay / 60));
  // Длинную статью не режем и не начинаем наполовину: обрезанная на
  // середине статья звучит как поломка, а не как исчерпанная квота.
  if (wantSeconds > left) {
    return t.audioTooLong(Math.floor(left / 60), Math.ceil(wantSeconds / 60));
  }
  return "";
}

/** Те строки словаря, которые нужны отказу. Больше он ни о чём не знает. */
export type AudioErrors = {
  audioOnPro: (plan: string) => string;
  audioNoTelegram: string;
  audioCapReached: (minutes: number) => string;
  audioTooLong: (left: number, needed: number) => string;
};

/**
 * Языки, где знак несёт куда больше звука, чем буква.
 *
 * Иероглиф — это слог или слово, а не буква, поэтому те же 880 знаков
 * в минуту дали бы оценку втрое короче правды, и статья на десять минут
 * прошла бы под квоту в три. Резать их тоже надо иначе: точка у них
 * полноширинная и пробела за собой не тянет.
 */
const DENSE = new Set(["японском", "китайском", "корейском"]);

/**
 * Сколько секунд будет звучать текст.
 *
 * Оценка до синтеза, чтобы не начинать то, на что не хватит квоты.
 * Числа замерены на живых описаниях: русский у этого голоса идёт
 * примерно 880 знаков в минуту, английский — 1005. Берётся русская,
 * то есть медленная: ошибиться в сторону «не хватит» дешевле, чем
 * оборвать статью на середине.
 */
export const estimateSeconds = (text: string, language = "русском"): number =>
  Math.ceil((text.length / (DENSE.has(language) ? 300 : 880)) * 60);

/** Сколько знаков уходит в один запрос к движку. */
const CHUNK = 2500;

/**
 * Разрезать текст на куски по границам предложений.
 *
 * Резать по знакам нельзя: разрыв посреди слова движок читает как два
 * обрубка, и это слышно. Предложение длиннее куска уезжает целиком —
 * лучше длинный запрос, чем разорванная фраза.
 */
export function chunks(text: string, limit = CHUNK): string[] {
  const out: string[] = [];
  let current = "";
  // Полноширинные знаки конца предложения режут и без пробела за ними:
  // у японского и китайского пробелов нет вовсе, и правило «точка плюс
  // пробел» отдавало бы весь текст одним куском.
  // Разделитель сохраняется: у латиницы после точки съедается пробел,
  // и вернуть его надо; у полноширинной точки пробела не было, и вставить
  // его значит развести иероглифы там, где их не разводят, — голос читает
  // это как паузу посреди фразы.
  for (const piece of text.split(/(?<=[.!?…])(\s+)|(?<=[。！？])()/).filter((p) => p !== undefined)) {
    if (piece === "") continue;
    if (/^\s+$/.test(piece)) continue;
    const glue = /[。！？]$/.test(current) ? "" : " ";
    if (current && current.length + piece.length + glue.length > limit) {
      out.push(current);
      current = piece;
    } else {
      current = current ? `${current}${glue}${piece}` : piece;
    }
  }
  if (current) out.push(current);
  return out;
}

/**
 * Словарь произношений из затравки, правила по буквам и того, что
 * накопилось в базе. Накопленное перекрывает затравку: словарь правится
 * данными, а не выкаткой.
 */
export function spokenMap(
  text: string,
  language: string,
  learned: Record<string, string> = {},
): Map<string, string> {
  const map = new Map<string, string>();
  for (const [key, value] of Object.entries(SEED_SPOKEN[language] ?? {})) map.set(key, value);
  for (const run of latinRuns(text)) {
    if (!spelledOut(run) || map.has(run.toLowerCase())) continue;
    const letters = byLetters(run, language);
    if (letters) map.set(run.toLowerCase(), letters);
  }
  for (const [key, value] of Object.entries(learned)) map.set(key.toLowerCase(), value);
  return map;
}
