/**
 * Читается ли кусок по буквам.
 *
 * Различает не длина, а гласные: `VHDL` и `SPL` читаются по буквам,
 * потому что их иначе не произнести, а `Gemini` и `Google` — словами.
 * Всё заглавными тоже читается по буквам (`API`, `GPU`), и это не то же
 * самое правило: `NASA` заглавными, но произносится словом — такие
 * исключения живут в словаре, а не в правиле.
 */
export function spelledOut(run: string): boolean {
  const letters = run.replace(/[^A-Za-z]/g, "");
  if (!letters) return false;
  if (!/[aeiouyAEIOUY]/.test(letters)) return true;
  return letters === letters.toUpperCase();
}

/**
 * Произношение по буквам: `VHDL` → «ви-эйч-ди-эль».
 *
 * Для языка, которому мы не знаем названий букв, возвращается пустая
 * строка: «не умею» должно отличаться от «прочитал». Вернуть латиницу
 * как есть значило бы сказать, что правило сработало, и такой термин
 * уже не попал бы в вопрос к модели.
 */
export function byLetters(run: string, language: string): string {
  const names = LETTERS[language];
  if (!names) return "";
  return run
    .split(/([-.+])/)
    .map((part) =>
      /^[-.+]$/.test(part)
        ? " "
        : part
            .split("")
            .map((ch) => names[ch.toLowerCase()] ?? ch)
            .join("-"),
    )
    .join("")
    .trim();
}

/**
 * Все различные латинские куски в порядке первой встречи.
 *
 * Различные — потому что спрашивать про `Google` по разу на каждое
 * упоминание значит платить за один и тот же ответ столько раз, сколько
 * раз журналист повторил название.
 */
export function latinRuns(text: string): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const m of text.matchAll(RUN)) {
    const key = m[0].toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(m[0]);
  }
  return out;
}

/**
 * Подставить произношение.
 *
 * Один проход тем же выражением, которым куски искались: подставлять
 * поиском по строке нельзя — `AI` лежит внутри `OpenAI`, и замена по
 * подстроке превратила бы его в «Оупенэй-ай» ровно там, где слово уже
 * разобрано правильно.
 *
 * Чего в словаре нет — остаётся как было. Пропущенный термин звучит
 * плохо, выдуманный звучит уверенно и неправильно.
 */
export function applySpoken(text: string, spoken: Map<string, string>): string {
  return text.replace(RUN, (run) => spoken.get(run.toLowerCase()) ?? run);
}

/**
 * Что из кусков этого текста мы ещё не умеем произносить.
 *
 * Читаемое по буквам считается известным: правило для него есть в коде
 * и оно не ошибается — спрашивать модель, как читается `VHDL`, значит
 * платить за то, что уже решено.
 */
export function unknownRuns(text: string, known: Map<string, string>): string[] {
  return latinRuns(text).filter((run) => !known.has(run.toLowerCase()));
}

