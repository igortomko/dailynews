/**
 * Бюджет внимания: сколько новостей в день отдано каждой теме.
 *
 * Хранится в `topics.weight` — там же, где раньше лежал множитель скора.
 * Число теперь означает буквально: цель по количеству материалов. Отбор
 * делит номер материала внутри темы на это число (pipeline/select.ts),
 * и при сумме целей, равной числу мест, каждая тема получает ровно свою
 * цель. Это единственная причина, по которой интерфейс может показывать
 * штуки, а не проценты.
 *
 * Мест столько, сколько уложится в заказанное время: заказ читателя —
 * минуты, а перевод в штуки делает `itemsForMinutes` по длине его же
 * описаний. Сумма целей приводится к этому числу на каждом входе.
 *
 * Цель — не обещание. Если материалов по теме за день меньше цели, место
 * уходит следующему по оценке, в том числе материалу вне тем. Обратное
 * было бы хуже: дайджест из десяти пустых мест ради ровного столбика.
 */

/** Меньше одной новости тема получить не может: ноль — это убрать тему. */
export const MIN_PER_TOPIC = 1;

/**
 * Цвета тем. Восемь фиксированных, по порядку: добавленная тема берёт
 * следующий, а уже заведённые свой не меняют. Равномерный разброс по кругу
 * пересчитывался бы при каждом добавлении, и все темы меняли бы цвет разом.
 */
export const TOPIC_COLORS = [
  "oklch(0.65 0.20 25)",
  "oklch(0.72 0.17 60)",
  "oklch(0.80 0.15 95)",
  "oklch(0.70 0.16 145)",
  "oklch(0.72 0.12 195)",
  "oklch(0.65 0.16 250)",
  "oklch(0.62 0.18 300)",
  "oklch(0.68 0.18 350)",
];

export const colorAt = (index: number) => TOPIC_COLORS[index % TOPIC_COLORS.length];

/**
 * Приводит цели к сумме, равной размеру дайджеста.
 *
 * Нужна на каждом входе, а не только при перетаскивании: темы добавляют
 * и убирают, размер дайджеста меняют, а в базе лежат цели от прошлого
 * набора. Без приведения сумма разъезжается с размером, и «10 из 20»
 * на экране означало бы не то, что получит читатель.
 *
 * Метод наибольших остатков: раздаём целые части пропорции, остаток —
 * по величине дробного хвоста. Простое округление каждой доли даёт сумму
 * то на единицу больше, то на единицу меньше.
 */
export function normalize(counts: number[], total: number): number[] {
  const n = counts.length;
  if (n === 0) return [];
  // Мест меньше, чем тем: у всех по одному. Сумма целей выйдет больше
  // размера дайджеста, и это не поломка — отбор всё равно режет по размеру,
  // а деление мест возвращается к прежнему ровному кругу. Показать кому-то
  // ноль было бы враньём: место он получить всё ещё может.
  if (total <= n) return counts.map(() => MIN_PER_TOPIC);

  const sum = counts.reduce((a, b) => a + b, 0);
  const shares = sum > 0 ? counts.map((c) => (c / sum) * total) : counts.map(() => total / n);

  const floors = shares.map((share) => Math.max(MIN_PER_TOPIC, Math.floor(share)));
  let left = total - floors.reduce((a, b) => a + b, 0);

  // Остаток раздаём по убыванию дробной части; нехватку снимаем с самых
  // больших, не опуская никого ниже минимума.
  const order = shares
    .map((share, index) => ({ index, frac: share - Math.floor(share) }))
    .sort((a, b) => b.frac - a.frac);

  for (let i = 0; left > 0 && i < order.length; i = (i + 1) % order.length) {
    floors[order[i].index]++;
    left--;
  }
  while (left < 0) {
    const biggest = floors.indexOf(Math.max(...floors));
    if (floors[biggest] <= MIN_PER_TOPIC) break;
    floors[biggest]--;
    left++;
  }
  return floors;
}

/**
 * Раздаёт бюджет между темами: недостачу снимает с самых жирных, излишек
 * отдаёт самым тощим.
 *
 * Это и есть правило полосы. Пока растущая тема отнимала у соседней, граница
 * упиралась в соседа с одной новостью и вставала намертво — при том, что
 * рядом лежали темы по шесть. Теперь платит самый крупный, и застрять можно
 * только когда справа у всех по минимуму.
 *
 * Отдаётся освободившееся место зеркально — самой тощей теме. Любое другое
 * правило для обратного хода делало бы гребок туда и обратно невосстановимым:
 * ушло бы у одного, вернулось бы другому.
 */
function level(parts: number[], budget: number): number[] {
  const next = [...parts];
  let left = budget - next.reduce((a, b) => a + b, 0);
  while (left > 0) {
    next[next.indexOf(Math.min(...next))]++;
    left--;
  }
  while (left < 0) {
    const fattest = next.indexOf(Math.max(...next));
    // Вызывающий обрезает запрос по сумме минимумов, так что сюда мы
    // не доходим. Без проверки цикл стал бы вечным, а не неточным.
    if (next[fattest] <= MIN_PER_TOPIC) break;
    next[fattest]--;
    left++;
  }
  return next;
}

/**
 * Двигает границу: тема слева от неё берёт ровно столько, сколько отмерил
 * курсор, а разницу отдают темы правее — начиная с самой жирной.
 *
 * Слева не берётся ничего, и это не выбор из двух: положение границы — это
 * сумма всего, что левее, поэтому отними место у темы левее — и сама граница
 * не сдвинется, то есть ручка отстанет от курсора.
 *
 * Сумма не меняется — значит, размер дайджеста не поедет от перетаскивания.
 */
export function moveBoundary(counts: number[], boundary: number, cumulative: number): number[] {
  const before = counts.slice(0, boundary).reduce((a, b) => a + b, 0);
  const rest = counts.slice(boundary + 1);
  const pool = counts[boundary] + rest.reduce((a, b) => a + b, 0);
  const target = Math.min(
    pool - MIN_PER_TOPIC * rest.length,
    Math.max(MIN_PER_TOPIC, Math.round(cumulative) - before),
  );
  return [...counts.slice(0, boundary), target, ...level(rest, pool - target)];
}

/**
 * Кнопки «+» и «−» на теме — та же полоса пальцем, поэтому и правило то же:
 * растущая тема ест самую жирную, а отданное место уходит самой тощей.
 * Разойдись они — одно и то же нажатие означало бы разное в двух местах
 * одного экрана.
 *
 * Упёрлось в предел — возвращаем тот же массив, а не молча другой: наверху
 * по нему решают, зажигать ли «Сохранить».
 */
export function nudgeTopic(counts: number[], index: number, by: number): number[] {
  const others = counts.filter((_, i) => i !== index);
  if (others.length === 0) return counts;
  const total = counts.reduce((a, b) => a + b, 0);
  const target = Math.min(
    total - MIN_PER_TOPIC * others.length,
    Math.max(MIN_PER_TOPIC, counts[index] + by),
  );
  const rest = level(others, total - target);
  return counts.map((_, i) => (i === index ? target : rest[i < index ? i : i - 1]));
}

/**
 * Где стоит ручка границы, в долях ширины полосы.
 *
 * Полоса сплошная: куски лежат вплотную, скруглены только её торцы, а каждая
 * граница помечена ручкой. Пока между кусками был зазор в четыре пиксела,
 * долю приходилось считать от цветной части и прибавлять к ней пройденные
 * зазоры — иначе ручка промахивалась тем сильнее, чем правее граница,
 * и у правого края уезжала на соседний сегмент. Зазоров не стало, и поправка
 * ушла вместе с ними: вернётся зазор — вернётся и она, а иначе промах
 * вернётся молча.
 */
export function handleLeft(counts: number[], boundary: number): string {
  const total = counts.reduce((sum, count) => sum + count, 0) || 1;
  const left = counts.slice(0, boundary + 1).reduce((sum, count) => sum + count, 0);
  return `${(left / total) * 100}%`;
}
