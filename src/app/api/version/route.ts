import { NextResponse } from "next/server";

/**
 * Какой код реально обслуживает запросы. Развёртывание сверяет ответ
 * с отправленным коммитом: тег образа на хосте исчезает при пересоздании
 * контейнера, а ответ сервиса — единственное, что нельзя подделать сборкой,
 * которая молча не собралась.
 */
export function GET() {
  return NextResponse.json({ commit: process.env.GIT_COMMIT ?? "unknown" });
}
