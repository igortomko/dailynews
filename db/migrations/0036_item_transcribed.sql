-- Отметка о том, что за расшифровкой ролика уже ходили.
--
-- Расшифровка шла только по материалам, вставленным этим же прогоном.
-- Стоило первой попытке не удаться — провайдер ответил 401, YouTube
-- отдал отказ, — и ролик оставался с описанием из фида навсегда:
-- в следующий прогон он уже не новый, и никто к нему не возвращается.
-- Выглядело это как обычный материал с коротким текстом, то есть ровно
-- так, как до всей затеи.
--
-- Время, а не флаг: видно, когда ходили, и можно спросить «давно ли».
-- Отметка ставится и когда субтитров нет вовсе — иначе такой ролик
-- опрашивался бы каждую ночь до конца окна свежести.
alter table dailynews.items
  add column if not exists transcribed_at timestamptz;

insert into dailynews.migrations (name) values ('0036_item_transcribed')
  on conflict (name) do nothing;
