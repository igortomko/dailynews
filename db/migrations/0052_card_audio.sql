-- Озвучка карточки, а не статьи за ссылкой.
--
-- 0045 ключевала аудио парой «материал + язык», потому что озвучивался
-- перевод статьи, а он общий по этой паре. На живом выпуске это оказалось
-- не тем: статья в 48 749 знаков — это 78 минут речи при дневной квоте
-- в 45, и кнопка отказывала почти на всём. При этом карточка над той же
-- кнопкой обещает «2 мин 10 с», и два числа в двух сантиметрах друг
-- от друга означали разное, не сказав об этом ни слова.
--
-- Читается то, что карточка и обещает: заголовок и описание. Тогда весь
-- выпуск («~46 мин» в шапке) укладывается в квоту Pro ровно — она под него
-- и считалась.
--
-- Ключ при этом обязан смениться. Описание живёт в `digest_items`
-- и персонально: два читателя на русском получают разные описания одной
-- новости, и общий ключ «материал + язык» отдал бы второму текст первого.
-- Это ровно тот отказ, что уже записан в AGENTS.md строкой «текст
-- дайджеста в общей `items`» — вовремя, без ошибок и не тот.
create table if not exists dailynews.card_audio (
  digest_id bigint not null references dailynews.digests (id) on delete cascade,
  item_id   bigint not null references dailynews.items (id) on delete cascade,
  file_id   text not null,
  seconds   integer not null,
  voice     text not null,
  at        timestamptz not null default now(),
  primary key (digest_id, item_id)
);

-- Прежняя таблица снимается: она хранит озвучку статьи, которой больше
-- не бывает, и четыре строки в ней — следы проверки на живых данных.
-- Оставить её значит держать вторую правду о том, что такое «озвучка
-- материала», и однажды прочитать не ту.
drop table if exists dailynews.item_audio;

insert into dailynews.migrations (name) values ('0052_card_audio')
  on conflict (name) do nothing;
