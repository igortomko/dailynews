-- Название бразильского португальского стало короче: «португальском
-- (бразильский вариант)» → «португальском (бразильский)».
--
-- Эта строка не только показывается: по ней ищутся скорость чтения, словарь
-- поиска Postgres и флажок. Переименование в коде без переписывания колонки
-- оставило бы выбравшего её читателя вне всех трёх словарей сразу — время
-- выпуска посчиталось бы русской меркой, поиск взял бы русский стеммер,
-- флажок исчез. Ни одной ошибки при этом не возникло бы.
--
-- Колонка свободная (0014 сняла с неё список), поэтому чинится обычным
-- update. Повторное применение безвредно: старого написания после первого
-- прохода не остаётся.
update dailynews.readers
   set language = 'португальском (бразильский)'
 where language = 'португальском (бразильский вариант)';

insert into dailynews.migrations (name) values ('0043_pt_br_label')
  on conflict (name) do nothing;
