-- Настройка Kindle — два шага, и второй нечем проверить снаружи.
--
-- Первый шаг мы видим сами: адрес читалки вписан. Второй — «читатель добавил
-- наш обратный адрес в список одобренных Amazon» — не виден никак: Amazon
-- не отвечает об этом ничем, а неодобренное письмо отбрасывается молча.
-- Значит шаг закрывает сам читатель, и это отдельный флаг, а не догадка
-- по другим колонкам.
--
-- Флаг заодно решает, можно ли ещё менять обратный адрес. До одобрения
-- можно: он ещё нигде не записан. После — смена означает молчаливую потерю
-- доставки, потому что в Amazon останется одобренным прежний.
alter table dailynews.readers
  add column if not exists kindle_approved boolean not null default false;

insert into dailynews.migrations (name) values ('0022_kindle_approved')
  on conflict (name) do nothing;
