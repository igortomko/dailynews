-- Отметка о том, что за текстом статьи уже ходили.
--
-- Материал приезжал в оценку и в дайджест тем, что отдал фид, а фид часто
-- не отдаёт ничего: у Hacker News описания нет по устройству API — 138
-- материалов из 147 за трое суток пришли с пустым excerpt, — а рассылка
-- кладёт в него служебную строку вроде «Community Wisdom 298», двадцать
-- знаков. Дальше по потоку это выглядело как работающий продукт: Jev
-- оценивал материал по одному заголовку, дайджест по нему же писал
-- «конспект», и читатель получал гладкий текст, из которого нельзя узнать,
-- что в статье. В выпуске 20 сентября описание было длиннее источника
-- у 37 материалов из 40.
--
-- Время, а не флаг: видно, когда ходили, и можно спросить «давно ли».
-- Отметка ставится и когда текст забрать не вышло — платный доступ,
-- антибот, страница без статьи, — иначе такой материал опрашивался бы
-- каждую ночь до конца окна свежести, и каждая ночь стоила бы тех же
-- запросов ради того же отказа.
alter table dailynews.items
  add column if not exists enriched_at timestamptz;

insert into dailynews.migrations (name) values ('0039_item_enriched')
  on conflict (name) do nothing;
