-- Сюжет карточки: сам материал вместе со своими повторами.
--
-- Дедуп до сих пор работал молча — повторы исчезали, и читателю неоткуда
-- было узнать, что одну и ту же новость ему не показали пять раз. Теперь
-- лента спрашивает базу «что ещё было про это», и спрашивает на каждую
-- карточку выпуска: до сорока раз на страницу.
--
-- Ключ сюжета — coalesce(dup_of, id): у оригинала это он сам, у повтора —
-- его оригинал. Без индекса по этому выражению каждый такой вопрос читает
-- items целиком; сегодня это четыреста строк, через год — пятьдесят тысяч,
-- и лента начнёт тормозить ровно тогда, когда смотреть на неё будет некогда.
--
-- Индекс по выражению, а не по dup_of: искать надо обе половины сюжета
-- одним условием, иначе запрос распадается на «оригинал или его повторы»,
-- и планировщик перестаёт видеть в этом одно обращение.
create index if not exists items_story_idx
  on dailynews.items ((coalesce(dup_of, id)));

insert into dailynews.migrations (name) values ('0041_story_index')
  on conflict (name) do nothing;
