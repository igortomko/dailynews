-- Галочка сети больше не решает судьбу адреса.
--
-- До этой миграции «публикую здесь» и «вот мой канал, читайте» были одной
-- строкой: снял галочку — строка удалена вместе с адресом. 22 сентября 2026
-- владелец снял и вернул галочку Telegram, разглядывая новый экран,
-- и `@publicigor` исчез: ни ошибки, ни предупреждения, а голос перечитать
-- уже нечем. Его пришлось заводить заново вручную.
--
-- Теперь это два разных ответа. Строка есть — мы знаем адрес и читаем
-- оттуда его посты; `publishes` — рисовать ли таб в черновике. Убрать адрес
-- стало отдельным действием, и стоит оно там же, где адрес показан.
--
-- Значение по умолчанию — `true`: каждая существующая строка была отмечена
-- галочкой, иначе её бы не существовало.
alter table dailynews.reader_channels
  add column if not exists publishes boolean not null default true;

insert into dailynews.migrations (name) values ('0058_reader_channels_publishes')
  on conflict (name) do nothing;
