-- Удалённый профиль обезличивается, а не стирается строкой.
--
-- Всё личное (Telegram, ник, описание, Kindle, соцсети, черновики, темы,
-- источники, правила, выпуски) стирается сразу, а безымянная строка
-- остаётся: на `readers.id` каскадом висят расход на модели и события
-- чтения, из них строятся «Расходы на LLM» и воронка в дашборде. Стёртая
-- строка переписала бы обе задним числом — «вошло 12» стало бы «вошло 11»,
-- а месяц подешевел бы на чужую долю.
--
-- Отметка, а не флаг: когда удалил, иногда важно для разбора.
alter table dailynews.readers
  add column if not exists deleted_at timestamptz;

insert into dailynews.migrations (name) values ('0063_readers_deleted_at')
  on conflict (name) do nothing;
