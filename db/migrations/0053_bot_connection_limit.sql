--
-- Веб переезжает на сессионный пулер (порт 5432): там prepared statements
-- работают, и каждый запрос с параметрами уходит одним кругом до базы
-- вместо двух (src/lib/db.ts). Плата сессионного режима — соединение
-- к Postgres занято, пока живёт клиентское, а веб держит их тёплыми
-- (до пяти, DB_POOL_MAX). Ночной прогон берёт ещё пять через транзакционный
-- пулер, и десяти ровно хватало бы на них двоих — скрипту (`npm run ping`)
-- в этот момент места не оставалось. У сервера 60 соединений, занято
-- около двадцати всеми продуктами вместе.
--
-- Роль, а не схема: сверка формы схемы про это не знает, файл выполняется
-- как тихий.
