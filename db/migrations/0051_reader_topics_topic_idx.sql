-- Индекс по теме в связках читателей с темами.
--
-- Первичный ключ связки — (reader_id, topic_id), и вопрос «кто ещё взял
-- эту тему» по нему не ищется: Postgres индексы по внешним ключам сам
-- не заводит. Вопрос задаётся дважды на каждое сохранение интересов
-- (`upsertTopic`: не переписать ли имя и подсказку темы, которую взял
-- ещё кто-то) и на каждого читателя каждым прогоном (`getReaderTopics`
-- отдаёт признак `shared`). Без индекса это чтение всей таблицы связок
-- на каждый вопрос — сегодня десятки строк, через год тысячи.
--
-- Миграция из одного индекса: сверка формы схемы его не видит, и в журнал
-- он попадает выполнением, а не по обещанию (урок 0041). Проверять
-- в pg_indexes — так делает `npm run verify:db`.
create index if not exists reader_topics_topic_idx
  on dailynews.reader_topics (topic_id);

insert into dailynews.migrations (name) values ('0051_reader_topics_topic_idx')
  on conflict (name) do nothing;
