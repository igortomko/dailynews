-- Когда боту последний раз говорили про тариф.
--
-- Колонкой, а не счётом по журналу: сказать об этом больше негде, а считать
-- «раз в неделю» от даты выпуска значило бы привязать молчание к тому,
-- собрался ли выпуск, — в тихий день отсчёт съезжал бы сам.
--
-- В ленте такой отметки нет и не нужно: строка под выпуском попадается
-- на глаза только тому, кто сам пришёл читать. В чат сообщение приходит
-- само, и каждую ночь это спам.
alter table dailynews.readers
  add column if not exists upsell_at timestamptz;

comment on column dailynews.readers.upsell_at is
  'Когда в чате последний раз говорили про тариф. Молчим неделю после (UPSELL_QUIET_DAYS).';
