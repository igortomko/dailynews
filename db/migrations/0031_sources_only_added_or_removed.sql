-- У источника два состояния, а не три.
--
-- Переключатель из интерфейса убран: решений с источником ровно два —
-- завести и убрать. Но колонка active осталась, и вместе с ней осталось
-- третье состояние, из которого нет выхода: тринадцать источников лежали
-- выключенными, включить их было нечем, а прогон их не читал. В списке они
-- выглядели живыми.
--
-- Выключенные убираются — мягко, как и всё остальное с 0030: материалы,
-- чтения и записи в прошлых выпусках остаются на месте, а сам источник
-- исчезает из списка и из прогона.
update dailynews.sources
   set deleted_at = now()
 where deleted_at is null
   and (
     not active
     -- Reddit и X убираются и на чистой базе тоже. 0006 выключала Reddit
     -- и заводила X включённым; на живой базе к этому дню выключены оба,
     -- и без этой строки новая установка расходилась бы с продом: там
     -- источников X нет, а тут они есть и стоят денег с первого прогона.
     -- Reddit без ключей Data API отвечает 429 на втором сабреддите,
     -- X — 402, когда у перепродавца кончился баланс. Понадобятся — заводятся
     -- ссылкой, как всё остальное.
     or kind in ('reddit', 'x')
   );

-- Оставшиеся выравниваются в одно значение: с этого момента active никто
-- не читает, «опрашивается» означает «не убран».
update dailynews.sources set active = true where deleted_at is null;

-- Колонка не удаляется намеренно. 0006 выключает ею Reddit, а db/verify.ts
-- прогоняет миграции дважды подряд, проверяя идемпотентность: без колонки
-- второй заход упал бы на чужой, давно применённой миграции. Убрать её
-- можно будет, когда старые миграции схлопнут в одну.
comment on column dailynews.sources.active is
  'Наследие переключателя. Всегда true у неубранных; состояние источника задаёт deleted_at.';

insert into dailynews.migrations (name) values ('0031_sources_only_added_or_removed')
  on conflict (name) do nothing;
