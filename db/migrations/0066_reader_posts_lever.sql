-- Каким рычагом прокачан второй вариант черновика.
--
-- Первый вариант пишется «как он», второй — тем же голосом плюс один рычаг
-- из корпуса виральных постов (число в первой строке, признание, вердикт,
-- названный круг, конкретика). Без колонки выбор между ними — это «взял
-- второй», а не «взял число в первой строке»: какой рычаг работает у него,
-- а не в среднем по чужим каналам, узнать было бы не из чего.
alter table dailynews.reader_posts
  add column if not exists lever text;

insert into dailynews.migrations (name) values ('0066_reader_posts_lever')
  on conflict (name) do nothing;
