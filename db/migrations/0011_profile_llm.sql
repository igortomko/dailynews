-- Свой ключ модели для дайджеста. До сих пор он приходил только из окружения,
-- то есть менялся через правку секретов и передеплой. Здесь он становится
-- настройкой продукта.
--
-- Ключ лежит в базе открытым текстом. Это осознанный размен: схема не
-- экспонируется наружу, у роли нет доступа к чужим схемам, а читатель один
-- и ключ его собственный. Путь через окружение остаётся: он старше по
-- приоритету и не требует базы вовсе.
alter table dailynews.profile
  add column if not exists llm jsonb not null default '{}'::jsonb;

insert into dailynews.migrations (name) values ('0011_profile_llm')
  on conflict (name) do nothing;
