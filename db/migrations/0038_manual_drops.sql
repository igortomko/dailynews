-- Материал, бро́шенный владельцем боту: ссылка, ролик, чужой пост или
-- собственная мысль.
--
-- Кладётся в `items` наравне с приехавшим из фида, а не в отдельную таблицу.
-- Причина: всё, что висит ниже материала, уже написано под `items.id` —
-- черновики (`reader_posts.item_id`), сверка чисел с текстом источника,
-- отметка взятого варианта и его правка. Своя таблица потребовала бы второго
-- пути в каждом из этих мест, а отличается брошенное от собранного ровно
-- одним полем — источником.
--
-- `url_canon` у мысли настоящего адреса не имеет, поэтому синтетический
-- `drop://<вид>/<хеш текста>`: уникальность нужна не ради ссылки, а чтобы
-- дважды брошенная мысль не заводила второй материал.
--
-- Ограничение зовётся sources_kind_known с 0025 и перечисляет все виды
-- целиком: добавить вид — значит переписать список, а не добавить второе
-- ограничение рядом. Второе молча запретило бы telegram и email, и увидели
-- бы это не здесь, а на первом добавленном канале.
alter table dailynews.sources drop constraint if exists sources_kind_known;
alter table dailynews.sources
  add constraint sources_kind_known
  check (kind in ('rss', 'hackernews', 'reddit', 'x', 'telegram', 'email', 'manual'));

-- Строку самого источника миграция не заводит, и это не забывчивость.
-- Миграции применяются повторно целиком, и 0026 при повторе заново вешает
-- свой список видов, где `manual` ещё нет: существующая строка нового вида
-- не даст его создать, и упадёт весь прогон. Поэтому источник «Свои входы»
-- создаётся кодом при первом брошенном материале — тем же способом, каким
-- появляются почтовые источники.

insert into dailynews.migrations (name) values ('0038_manual_drops')
  on conflict (name) do nothing;
