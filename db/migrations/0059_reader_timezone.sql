-- Выпуск собирается в 02:00 по времени читателя, а не в одно окно на всех.
--
-- Пояс — имя IANA ('America/Sao_Paulo'), а не смещение: смещение меняется
-- с переходом на летнее время, и выпуск уезжал бы на час дважды в год.
-- Пусто — пояс ещё не определён браузером; читается как Сан-Паулу,
-- то есть ровно то время, в которое выпуск приходил до этой колонки.
-- Проверяется в коде (`Intl`), а не ограничением: список поясов живёт
-- в ICU и обновляется вместе с Node, а не с базой.
alter table dailynews.readers
  add column if not exists timezone text;

-- Местный день, за который выпуск уже брался. Ставится до сборки одним
-- `update … returning`: таймер в вебе и прогон в Actions приходят
-- к одному читателю независимо, и выпуск достаётся тому, кто поставил
-- отметку первым. Ставится и тогда, когда выпуска не вышло (не его день
-- на бесплатном, пауза, потолок): иначе каждые десять минут до конца
-- суток повторялась бы та же проверка и та же строка в логе.
alter table dailynews.readers
  add column if not exists issue_day date;

insert into dailynews.migrations (name) values ('0059_reader_timezone')
  on conflict (name) do nothing;
