-- Сколько источник молчит подряд.
--
-- last_count писался с самого начала, но на него никто не смотрел. Источник,
-- отвечающий 200 и отдающий ноль свежих записей несколько дней подряд, —
-- самая незаметная поломка в ленте: ошибки нет, вкладка открывается,
-- дайджест приходит, просто одного голоса в нём больше не слышно.
--
-- Отметка времени, а не счётчик: прогон могут запустить дважды за сутки,
-- и счётчик посчитал бы два дня тишины за один. Пишется при первом пустом
-- прогоне, снимается при первой же записи.
alter table dailynews.sources
  add column if not exists silent_since timestamptz;

insert into dailynews.migrations (name) values ('0020_source_silence')
  on conflict (name) do nothing;
