-- Pro становится тарифом для блогера.
--
-- Номер 0036, а не 0034: журнал живой базы уже держит 0034 из ветки
-- онбординга и 0035 из ветки конспектов роликов. Два файла под одним
-- номером расходятся тем тише, чем дольше их не сводить.
--
-- Plus — для тех, кто читает: каждый день, сорок источников, книга на Kindle.
-- Pro — для тех, кто пишет: из той же ленты он получает готовый пост своим
-- голосом для каждой своей сети.
--
-- Три вещи, которых для этого не было в базе.
--
-- 1. Его площадки. Список нужен дважды и для разного: откуда мы читаем его
--    текст (публичный канал Telegram, RSS блога, твиты) и куда он публикует
--    (там же плюс LinkedIn и Threads, которые наружу не отдают ничего).
--    Одна таблица, потому что это один список в его голове — «мои каналы»;
--    что из них читаемо, решает код по виду сети, а не колонка. Вторая
--    таблица «куда публикую» разъехалась бы с первой на второй же правке.
--
-- 2. Карточка автора. Голос (как он пишет) и каркас (чем его удачные посты
--    отличаются от средних) считаются один раз и лежат готовыми: они уходят
--    в промпт на каждое нажатие, и считать их заново каждый раз — это платить
--    за один и тот же ответ столько раз, сколько он нажмёт.
--    Замерено 19 сентября 2026: карточка по двадцати постам — 3 270 токенов
--    входа и 1 076 выхода, $0.0011. Один пост в три сети — $0.0007.
--
-- 3. Черновики. Хранятся все, помечается взятый, и рядом ложится текст,
--    который он в итоге скопировал. Разница между нашим черновиком и его
--    правкой — единственный сигнал о его вкусе, который вообще существует,
--    и восстановить его задним числом нельзя: не сохранили при нажатии —
--    не узнаем никогда.

-- Площадки читателя.
--
-- handle пустой у сетей, где читать нечего (LinkedIn, Threads): строка там
-- означает ровно «я тут публикую, дай мне таб». Уникальность по паре
-- (читатель, сеть): второй телеграм-канал у блогера бывает, но голос
-- собирается с основного, а два канала под одним голосом — это уже
-- не настройка, а отдельное решение.
create table if not exists dailynews.reader_channels (
  reader_id  bigint not null references dailynews.readers (id) on delete cascade,
  network    text not null check (network in ('telegram', 'x', 'linkedin', 'threads', 'blog')),
  -- Разрешённый адрес: имя канала, адрес фида, запрос from:имя. Пусто —
  -- читать нечего, строка означает только «дай мне таб этой сети».
  handle     text,
  -- Что он вставил, до разбора. Рядом с разрешённым по той же причине,
  -- по которой это сделано у источников: без исходной строки в списке
  -- остаётся адрес фида, которого он никогда не видел.
  input_url  text,
  label      text,
  created_at timestamptz not null default now(),
  primary key (reader_id, network)
);

alter table dailynews.readers
  -- Карточка автора: {voice, frame, taboo, built_from, sources}.
  -- jsonb объектом, а не строкой: JSON.stringify в jsonb кладёт строку,
  -- и voice_card->'voice' молча становится null (урок 0005).
  add column if not exists voice_card jsonb,
  add column if not exists voice_built_at timestamptz,
  -- Вставленные руками посты. Нужны тем, у кого нечего читать: LinkedIn
  -- не отдаёт ленту вовсе, а блогер без публичного канала — обычное дело.
  -- Без этой колонки у него оставался бы выбор между пустой карточкой
  -- и чужим голосом.
  add column if not exists voice_sample text not null default '';

-- Черновики постов.
--
-- text — что предложила модель, taken_text — что он скопировал (пусто, если
-- не правил). Просмотры дописываются позже, когда пост найдётся в его канале:
-- сравнивать наши посты с его обычными можно только по опубликованному,
-- и раньше десятка пар это шум, а не измерение.
create table if not exists dailynews.reader_posts (
  id         bigint generated always as identity primary key,
  reader_id  bigint not null references dailynews.readers (id) on delete cascade,
  item_id    bigint not null references dailynews.items (id) on delete cascade,
  network    text not null,
  -- Вариантов два, и отличаются они первой строкой: выбор между ними —
  -- единственный сигнал о его вкусе, который не стоит ни копейки.
  variant    smallint not null default 1,
  text       text not null,
  -- Оси качества поста теми же шестью вопросами, что у описаний, плюс
  -- контрольная «голос»: пост, выигравший по пяти осям и проигравший
  -- по шестой, — это чужой хороший пост под его именем.
  axes       jsonb,
  score      real,
  taken_at   timestamptz,
  taken_text text,
  -- Найденный в его канале опубликованный пост и его просмотры.
  published_url text,
  views      int,
  checked_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists reader_posts_reader_idx
  on dailynews.reader_posts (reader_id, created_at desc);
-- Взятые посты — та выборка, по которой считается виральность. Частичный
-- индекс, потому что остальные черновики в этом вопросе не участвуют.
create index if not exists reader_posts_taken_idx
  on dailynews.reader_posts (reader_id, taken_at) where taken_at is not null;

-- Карточка автора и сам пост — оплаченные вызовы, и они обязаны попадать
-- в тот же счётчик, по которому считается дневной потолок. Этапа, которого
-- нет в ограничении, запись не переживёт: упадёт вставка расхода, а с ней
-- и ответ читателю, уже оплаченный (урок 0027).
--
-- Список перечисляется целиком, и это ограничение уже переопределяли из двух
-- ветвей: 0027 добавила перевод, 0035 — конспект ролика ('video'). Такое
-- переопределение не видно ни одной проверке, поэтому свои этапы дописываются
-- вместе с чужими, а не вместо них: ветка, перечислившая только своё, молча
-- гасит соседям запись расхода на живой базе. Именно так и вышло при первом
-- применении этого файла — 'video' пропал у ветки, которая стояла на проде.
alter table dailynews.model_calls drop constraint if exists model_calls_stage_check;
alter table dailynews.model_calls
  add constraint model_calls_stage_check
  check (stage in ('score', 'digest', 'summary', 'translate', 'translation-quality',
                   'video', 'voice', 'post', 'post-quality'));

insert into dailynews.migrations (name) values ('0036_blogger')
