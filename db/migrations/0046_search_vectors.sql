-- Хранимые tsvector для поиска по архиву.
--
-- Поиск считал to_tsvector по всем выпускам читателя на каждый запрос:
-- 50 мс на двухстах строках и рост линейный — к девяноста дням архива
-- около секунды на каждое слово. Вся цена запроса — разбор текста
-- и стемминг; само сопоставление на тысячах строк стоит микросекунды.
--
-- Два вектора, потому что два текста: написанное для читателя лежит
-- в digest_items (title, summary), исходное — в items (title, excerpt).
-- Generated columns, а не запись из кода: заголовок и описание выпуска
-- пишут ночной прогон, догрузка и «переписать голосом», excerpt меняет
-- догрузка статьи, — колонка, которую заполняет код, отставала бы
-- от текста на первом же забытом месте.
--
-- Словарь один, russian, и он же стоит в запросе (SEARCH_CONFIG
-- в src/lib/search.ts): вектор и запрос обязаны разбираться одним
-- словарём, а generated column требует константы. Русская конфигурация
-- разбирает латиницу тем же английским стеммером, что и английская
-- (замер в AGENTS.md, «Поиск по прошлым выпускам»), поэтому английские
-- слова ищутся как раньше; хуже станет только португальскому или испанскому
-- читателю, которого пока нет. Понадобится — словарь на выпуск хранится
-- колонкой regconfig и уходит в выражение вместо константы.
--
-- Индексов нет намеренно: запрос уже сужен читателем до его выпусков,
-- это тысячи строк, и GIN добавил бы обслуживание индекса на каждую
-- запись ради микросекунд на чтении.
alter table dailynews.digest_items
  add column if not exists tsv tsvector
    generated always as (
      to_tsvector('russian'::regconfig, coalesce(title, '') || ' ' || coalesce(summary, ''))
    ) stored;

alter table dailynews.items
  add column if not exists tsv tsvector
    generated always as (
      to_tsvector('russian'::regconfig, coalesce(title, '') || ' ' || coalesce(excerpt, ''))
    ) stored;

insert into dailynews.migrations (name) values ('0046_search_vectors')
  on conflict (name) do nothing;
