-- Длина текста статьи без разметки — хранимой колонкой.
--
-- Лента показывала «~6 мин», считая length(regexp_replace(body, '<[^>]*>',
-- '', 'g')) на каждый показ: пятьдесят статей по 12 КБ разметки в среднем
-- (до 61 КБ) — 12 мс из 16 мс запроса ленты, ради подписи, которую видно
-- только по наведению. Число меняется вместе с body и больше ни от чего
-- не зависит; считать его заново на каждом показе незачем.
--
-- Generated column, а не запись из кода: body пишут три места — фид,
-- догрузка статьи и пересказ ролика, — и колонка, которую заполняет код,
-- разошлась бы с текстом на первом же забытом месте. Postgres пересчитывает
-- её сам при каждой записи body. Null у материала без текста остаётся
-- null: length(null) — null, и лента по-прежнему молчит о времени чтения.
alter table dailynews.items
  add column if not exists body_chars int
    generated always as (length(regexp_replace(body, '<[^>]*>', '', 'g'))) stored;

insert into dailynews.migrations (name) values ('0045_item_body_chars')
  on conflict (name) do nothing;
