-- Удаление, которое можно отменить.
--
-- Раньше корзина в списке делала delete, а items.source_id стоит на
-- on delete cascade: одно нажатие уносило все собранные материалы, их оценки,
-- их чтения и их записи в уже отправленных выпусках. У Simon Willison это
-- двадцать материалов, восемь записей в прошлых выпусках и сто семьдесят
-- шесть чтений — то есть сигнал калибровки, на котором держится весь отбор.
-- Подтверждения не было, а кнопка стояла в ряду, где всё остальное только
-- показывает.
--
-- Отменить каскадное удаление нельзя ничем: восстановить строку источника
-- легко, а чтения и выпуски — уже нет. Поэтому удаление перестаёт удалять.
-- Источник помечается и исчезает отовсюду: из списка, из прогона, из счёта
-- по тарифу. История остаётся на месте, отмена возвращает ровно то, что было.
--
-- Активность при этом не трогается: пометка снимается — и источник
-- возвращается ровно в том состоянии, в каком был, а не «включённым вообще».
alter table dailynews.sources
  add column if not exists deleted_at timestamptz;

create index if not exists sources_live_idx
  on dailynews.sources (id) where deleted_at is null;

insert into dailynews.migrations (name) values ('0030_source_soft_delete')
  on conflict (name) do nothing;
